#!/usr/bin/env python3
"""Prepare, observe, or time the focused normal-pair candidates for #282.

This is a native Linux feasibility screen, not the native parity qualification.
Preparation needs the repository's generators-venv (pinned mpmath); observation
and timing use the Python standard library. Builds never run during timing.
"""
import argparse
import ctypes as ct
import hashlib
import json
import math
import os
from pathlib import Path
import platform
import shutil
import statistics
import struct
import subprocess

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
MASK = (1 << 64) - 1
N = 4096
BOUND = 2.0 ** -38
FUNCTIONS = ["candidate6", "candidate7", "strong", "libm_folded", "libm_direct"]


def run(argv, cwd=None, env=None, log_path=None):
    result = subprocess.run(argv, cwd=cwd, env=env, capture_output=True, text=True)
    output = result.stdout + result.stderr
    if log_path is not None:
        log_path.write_text(output)
    result.check_returncode()
    return output


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def splitmix(seed):
    while True:
        seed = (seed + 0x9E3779B97F4A7C15) & MASK
        z = seed
        z = ((z ^ (z >> 30)) * 0xBF58476D1CE4E5B9) & MASK
        z = ((z ^ (z >> 27)) * 0x94D049BB133111EB) & MASK
        yield (z ^ (z >> 31)) & MASK


def banks():
    words = splitmix(282)
    ordinary = [(next(words), next(words)) for _ in range(N)]
    edges = [0, MASK, 1 << 63, (1 << 63) - 1]
    radial = [(edges[i % len(edges)], next(words)) for i in range(N)]
    angles = [0, MASK]
    for octant in range(1, 8):
        angles += [(octant << 61) + delta for delta in [-2048, 0, 2048]]
    angular = [(next(words), angles[i % len(angles)]) for i in range(N)]
    return dict(ordinary=ordinary, radial_edges=radial, octant_edges=angular)


def prepare(out):
    import mpmath as mp
    if mp.__version__ != "1.4.1":
        raise RuntimeError("Use target/generators-venv/bin/python (mpmath 1.4.1)")
    out.mkdir(parents=True, exist_ok=False)
    templates = out / "templates"
    templates.mkdir()
    for name in ["screen.py", "candidate.rs", "native.c", "README.md"]:
        shutil.copy2(HERE / name, templates / name)
    source = out / "src"
    source.mkdir()
    mp.mp.prec = 200
    # The rounded angle is at most RN(pi/4); RN(pi/4) < the exact pi/4.
    upper = mp.mpf(float.fromhex("0x1.921fb54442d18p-1")) ** 2
    sine = lambda z: mp.sin(mp.sqrt(z)) / mp.sqrt(z) if z else mp.mpf(1)
    cosine = lambda z: mp.cos(mp.sqrt(z))
    text = "// Generated by scripts/bench_fast/normal_pair/screen.py at 200 bits.\n"
    coefficients = {}
    for n in [6, 7]:
        for name, f in [("SIN", sine), ("COS", cosine)]:
            values = list(reversed(mp.chebyfit(f, [0, upper], n)))
            rounded = [float(x) for x in values]
            text += f"const {name}{n}: [f64; {n}] = [\n"
            text += "".join(f"    f64::from_bits(0x{struct.pack('>d', x).hex()}),\n" for x in rounded)
            text += "];\n"
            coefficients[name + str(n)] = [x.hex() for x in rounded]
    (source / "coefficients.rs").write_text(text)
    (source / "lib.rs").write_bytes((HERE / "candidate.rs").read_bytes())
    manifest = '[package]\nname = "normal-pair-screen"\nversion = "0.0.0"\nedition = "2024"\n'
    manifest += '[lib]\ncrate-type = ["cdylib"]\n[workspace]\n[dependencies]\n'
    manifest += f'morphiq-numerics = {{ path = {json.dumps(str(ROOT / "crates/morphiq-numerics"))}, features = ["std", "simd"] }}\n'
    manifest += '[profile.release]\ncodegen-units = 1\nlto = "fat"\n'
    (out / "Cargo.toml").write_text(manifest)
    # Avoid inheriting feature flags which could change the declared sequence.
    env = os.environ.copy()
    env["RUSTFLAGS"] = "-C target-cpu=x86-64-v3"
    env["CARGO_TARGET_DIR"] = str(out / "target")
    rust = ["cargo", "build", "--offline", "--release", "--manifest-path", str(out / "Cargo.toml")]
    run(rust, env=env, log_path=out / "rust-build.log")
    native = out / "native.so"
    cc = ["cc", "-O3", "-march=x86-64-v3", "-ffp-contract=off", "-fno-math-errno",
          "-fno-builtin-log", "-fno-builtin-sincos",
          "-shared", "-fPIC", str(HERE / "native.c"), "-lm", "-o", str(native)]
    run(cc, log_path=out / "c-build.log")
    product = out / "target/release/libnormal_pair_screen.so"
    files = [*templates.iterdir(), source / "coefficients.rs", source / "lib.rs",
             out / "Cargo.toml", out / "Cargo.lock", native, product,
             ROOT / "crates/reference/fixtures/box_muller.json"]
    linked = run(["ldd", str(native)])
    for line in linked.splitlines():
        if "=>" in line:
            path = Path(line.split("=>", 1)[1].strip().split()[0])
            if path.is_file():
                files.append(path.resolve())
    inputs = {name: [[f"{a:016x}", f"{b:016x}"] for a, b in bank]
              for name, bank in banks().items()}
    (out / "inputs.json").write_text(json.dumps(inputs) + "\n")
    files.append(out / "inputs.json")
    metadata = dict(source=run(["git", "rev-parse", "HEAD"]).strip(),
                    source_diff=run(["git", "diff", "HEAD"]),
                    source_files={str(p.relative_to(ROOT)): digest(p)
                                  for p in (ROOT / "crates").rglob("*.rs")},
                    files={str(p): digest(p) for p in files}, coefficients=coefficients,
                    rustc=run(["rustc", "-Vv"]), cc=run(["cc", "--version"]),
                    native_linkage=linked,
                    libc=platform.libc_ver(), platform=platform.platform(),
                    cpu=Path("/proc/cpuinfo").read_text(),
                    rust_command=rust, rustflags=env["RUSTFLAGS"], cc_command=cc,
                    mpmath=mp.__version__, precision_bits=mp.mp.prec,
                    interpretation="Feasibility screen only. No proved bound or parity claim.")
    (out / "manifest.json").write_text(json.dumps(metadata, indent=2) + "\n")


class Pair(ct.Structure):
    _fields_ = [("x", ct.c_double), ("y", ct.c_double)]


def load(out):
    metadata = json.loads((out / "manifest.json").read_text())
    for path, expected in metadata["files"].items():
        if digest(Path(path)) != expected:
            raise RuntimeError(f"Frozen screen input changed: {path}")
    for path, expected in metadata["source_files"].items():
        if digest(ROOT / path) != expected:
            raise RuntimeError(f"Library source changed since build: {path}")
    product = ct.CDLL(str(out / "target/release/libnormal_pair_screen.so"))
    native = ct.CDLL(str(out / "native.so"))
    functions = {}
    for name in FUNCTIONS:
        f = getattr(product if name in FUNCTIONS[:3] else native, name)
        f.argtypes = [ct.c_uint64, ct.c_uint64]
        f.restype = Pair
        functions[name] = f
    return native, functions


def observe(out):
    _, functions = load(out)
    fixture = json.loads((ROOT / "crates/reference/fixtures/box_muller.json").read_text())
    cases = fixture["edges"] + [row for family in ["splitmix64", "xoshiro256pp"]
                                for stream in fixture[family].values() for row in stream]
    results = {}
    for name in FUNCTIONS:
        worst = (-1, None)
        for row in cases:
            words = [int(row[k], 16) for k in ["w1", "w2"]]
            expected = [struct.unpack(">d", bytes.fromhex(row[k]))[0] for k in ["z0", "z1"]]
            got = functions[name](*words)
            actual = [got.x, got.y]
            assert all(math.isfinite(v) for v in actual), (name, row, actual)
            if name == "strong":
                assert [struct.pack(">d", v).hex() for v in actual] == [row["z0"], row["z1"]]
            error = max(abs(a - b) for a, b in zip(actual, expected))
            if error > worst[0]:
                worst = error, row
            if name.startswith("candidate"):
                assert error <= BOUND, (name, words, actual, expected)
                for a, b in zip(actual, expected):
                    if b == 0.0:
                        assert struct.pack(">d", a) == struct.pack(">d", b), (name, row, actual)
        results[name] = dict(cases=len(cases), observed_max_absolute_error=worst[0],
                             witness=worst[1], reference="independent interval-oracle fixture",
                             candidate_target=BOUND, whole_domain_bound="unestablished")
    (out / "observations.json").write_text(json.dumps(results, indent=2) + "\n")
    print(json.dumps({name: row["observed_max_absolute_error"] for name, row in results.items()}, indent=2))


def measure(out, cpu, seconds, repetitions):
    if not (out / "observations.json").exists():
        raise RuntimeError("Run observe before timing")
    native, functions = load(out)
    os.sched_setaffinity(0, {cpu})
    native.measure.argtypes = [ct.c_void_p, ct.POINTER(ct.c_uint64), ct.POINTER(Pair),
                              ct.c_size_t, ct.c_uint64]
    native.measure.restype = ct.c_uint64
    inputs = json.loads((out / "inputs.json").read_text())
    # Exclusive creation preserves every pilot and timed attempt.
    with (out / "timings.jsonl").open("x", buffering=1) as log:
        def record(row):
            log.write(json.dumps(row) + "\n")
        record(dict(kind="host", cpu=cpu, load=os.getloadavg(),
                    seconds=seconds, repetitions=repetitions,
                    affinity=sorted(os.sched_getaffinity(0)),
                    clock="CLOCK_MONOTONIC", power_thermal_contention="uncontrolled",
                    order="alternating complete function order per repetition",
                    interpretation="screen; fixed-bank throughput, no stream/latency/SIMD qualification"))
        samples = {}
        for population, bank in inputs.items():
            n = len(bank)
            words = (ct.c_uint64 * (2*n))(*(int(w, 16) for pair in bank for w in pair))
            output = (Pair * n)()
            rounds = {}
            for name, f in functions.items():
                pilot = native.measure(f, words, output, n, 1)
                rounds[name] = max(1, int(seconds * 1e9 / pilot))
                record(dict(kind="pilot", population=population, function=name, ns=pilot,
                            pairs=n, rounds=1, selected_rounds=rounds[name]))
                native.measure(f, words, output, n, rounds[name])
            for repetition in range(repetitions):
                order = FUNCTIONS if repetition % 2 == 0 else FUNCTIONS[::-1]
                for name in order:
                    ns = native.measure(functions[name], words, output, n, rounds[name])
                    value = ns / (n * rounds[name])
                    record(dict(kind="sample", population=population, function=name,
                                repetition=repetition, ns=ns, rounds=rounds[name],
                                pairs=n, ns_per_pair=value))
                    samples.setdefault(population + "/" + name, []).append(value)
        summary = {key: dict(median_ns=statistics.median(xs), min_ns=min(xs), max_ns=max(xs))
                   for key, xs in samples.items()}
        record(dict(kind="final_host", load=os.getloadavg()))
    (out / "screen-summary.json").write_text(json.dumps(summary, indent=2) + "\n")
    print(json.dumps(summary, indent=2))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("action", choices=["prepare", "observe", "measure"])
    parser.add_argument("out", type=Path)
    parser.add_argument("--cpu", type=int)
    parser.add_argument("--seconds", type=float, default=0.03)
    parser.add_argument("--repetitions", type=int, default=7)
    args = parser.parse_args()
    if platform.system() != "Linux" or platform.machine() != "x86_64":
        parser.error("This screen currently requires native x86-64 Linux with AVX2/FMA")
    if args.action == "measure" and (args.cpu is None or args.seconds <= 0 or args.repetitions < 2):
        parser.error("Timing needs --cpu, positive --seconds and at least two repetitions")
    out = args.out.resolve()
    if args.action == "prepare":
        prepare(out)
    elif args.action == "observe":
        observe(out)
    else:
        measure(out, args.cpu, args.seconds, args.repetitions)


if __name__ == "__main__":
    main()
