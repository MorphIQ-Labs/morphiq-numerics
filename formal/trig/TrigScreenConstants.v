(** Small-input screen constants: exact runtime encodings, with analytic
    endpoint bounds. The thresholds are generated by sin_cos_reference.py. *)
From Coq Require Import Reals ZArith Lia Lra.
From Flocq Require Import Core IEEE754.Bits.
From Binary64 Require Import IEEE64 Encodings.
From Interval Require Import Tactic.
Open Scope R_scope.

Definition trig_sin_is_x := b64_of_bits 4492080543488425718.
Definition trig_sin_is_x_next := b64_of_bits 4492080543488425719.
Lemma trig_sin_is_x_finite : finite trig_sin_is_x.
Proof. exact (bits_finite 4492080543488425718 _ _ _ eq_refl). Qed.
Lemma trig_sin_is_x_value : B trig_sin_is_x=6495314627411702/2^78.
Proof. exact (bits_val 4492080543488425718 false 6495314627411702 78 eq_refl). Qed.
Lemma trig_sin_is_x_next_value : B trig_sin_is_x_next=6495314627411703/2^78.
Proof. exact (bits_val 4492080543488425719 false 6495314627411703 78 eq_refl). Qed.
Lemma trig_sin_is_x_bounds : bpow radix2 (-26)<B trig_sin_is_x<bpow radix2 (-25).
Proof. rewrite trig_sin_is_x_value;split;interval. Qed.
Lemma trig_sin_is_x_error :
 0<B trig_sin_is_x-sin(B trig_sin_is_x)<bpow radix2 (-79).
Proof. rewrite trig_sin_is_x_value;split;interval with (i_prec 220). Qed.
Lemma trig_sin_is_x_next_error :
 bpow radix2 (-79)<B trig_sin_is_x_next-sin(B trig_sin_is_x_next).
Proof. rewrite trig_sin_is_x_next_value;interval with (i_prec 220). Qed.

Definition trig_cos_step_bits (k:nat) : Z :=
 match k with
 | O => 4487450680906169292
 | S O => 4491100989407437102
 | S (S O) => 4492706045107002194
 | _ => 4494010692267425609
 end.
Definition trig_cos_step k := b64_of_bits (trig_cos_step_bits k).
Definition trig_cos_step_next k := b64_of_bits (trig_cos_step_bits k+1).
Definition trig_cos_step_real (k:nat) : R :=
 match k with
 | O => 6369051672525772/2^79
 | S O => 5515760546423086/2^78
 | S (S O) => 7120816245988178/2^78
 | _ => 8425463406411593/2^78
 end.
Definition trig_cos_step_next_real (k:nat) : R :=
 match k with
 | O => 6369051672525773/2^79
 | S O => 5515760546423087/2^78
 | S (S O) => 7120816245988179/2^78
 | _ => 8425463406411594/2^78
 end.
Lemma trig_cos_step_finite k : finite (trig_cos_step k).
Proof. destruct k as [|[|[|k]]];vm_compute;reflexivity. Qed.
Lemma trig_cos_step_value k : B (trig_cos_step k)=trig_cos_step_real k.
Proof. destruct k as [|[|[|k]]];unfold trig_cos_step,trig_cos_step_bits,trig_cos_step_real;rewrite pow_IZR;reflexivity. Qed.
Lemma trig_cos_step_next_value k : B (trig_cos_step_next k)=trig_cos_step_next_real k.
Proof. destruct k as [|[|[|k]]];unfold trig_cos_step_next,trig_cos_step_bits,trig_cos_step_next_real;rewrite pow_IZR;reflexivity. Qed.
Lemma trig_cos_step_bounds k :
 bpow radix2 (-27)<B(trig_cos_step k)<B(trig_cos_step_next k) /\
 B(trig_cos_step_next k)<bpow radix2 (-25).
Proof.
 rewrite trig_cos_step_value,trig_cos_step_next_value.
 destruct k as [|[|[|k]]];cbn [trig_cos_step_real trig_cos_step_next_real];repeat split;interval with (i_prec 100).
Qed.
Lemma trig_cos_step_lower k : (k<4)%nat ->
 1-(2*INR k+1)*bpow radix2 (-54)<cos(B(trig_cos_step k)).
Proof.
 intro K;rewrite trig_cos_step_value.
 destruct k as [|[|[|[|k]]]];try lia;cbn [trig_cos_step_real INR];interval with (i_prec 220).
Qed.
Lemma trig_cos_step_next_upper k : (k<4)%nat ->
 cos(B(trig_cos_step_next k))<1-(2*INR k+1)*bpow radix2 (-54).
Proof.
 intro K;rewrite trig_cos_step_next_value.
 destruct k as [|[|[|[|k]]]];try lia;cbn [trig_cos_step_next_real INR];interval with (i_prec 220).
Qed.
Lemma trig_cos_small_lower :
 1-9*bpow radix2 (-54)<cos(bpow radix2 (-25)).
Proof. interval with (i_prec 220). Qed.
