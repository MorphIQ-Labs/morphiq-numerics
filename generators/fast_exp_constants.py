#!/usr/bin/env python3
"""1024-way bounded exp constants, independently checked by Coq.

Generate at 600 bits, round once using exp_constants' integer nearest-even
routine, and retain a double-word table for TableCheck's reflective proof.
Only the prebiased high words enter the runtime. The constrained cubic keeps
exp(0)=1: minimizing max |t*t-alpha*t| on [0,1] gives
alpha=2*(sqrt(2)-1), by equating 1-alpha and alpha*alpha/4.
The public quadratic also preserves exp(0)=1. Its linear coefficient
1+A^2/8 makes the leading residual r^3/6-A^2*r/8 a scaled Chebyshev T3,
whose maximum magnitude on [-A,A] is A^3/24.
"""
from pathlib import Path
import struct
import sys

import mpmath as mp
from exp_constants import rn_bits, to_bits

ROOT = Path(__file__).resolve().parents[1]
PREC = 600
RADIUS = '0.000338451'


def coq_constant(name, value):
    word = to_bits(value)
    negative = value < 0
    mantissa = (word & ((1 << 52) - 1)) | (1 << 52)
    denominator = 1075 - ((word >> 52) & 2047)
    sign = 'true' if negative else 'false'
    numerator = f'(- {mantissa})' if negative else str(mantissa)
    return f'''Definition {name} : f64 := b64_of_bits {word}.
Lemma {name}_val : B {name} = {numerator} / 2 ^ {denominator}.
Proof. exact (bits_val {word} {sign} {mantissa} {denominator} eq_refl). Qed.
Lemma {name}_finite : finite {name}.
Proof. exact (bits_finite {word} _ _ _ eq_refl). Qed.
'''


def outputs():
    with mp.workprec(PREC):
        step = mp.log(2) / 1024
        inv = rn_bits(1 / step, 53)
        l1 = rn_bits(step, 31)
        l2d = rn_bits(step - l1, 53)
        c2 = rn_bits(mp.mpf('.5') + 2*(mp.sqrt(2)-1)*mp.mpf(RADIUS)**2/24, 53)
        step_word = rn_bits(step, 53)
        c1 = rn_bits(1 + mp.mpf(RADIUS)**2/8, 53)
        # The double-word exponential's three-part Cody-Waite step: n*L1 and
        # n*L2 are exact for |n| < 2^22, and n*L3 is taken by an exact product.
        dw_l2 = rn_bits(step - l1, 31)
        dw_l3 = rn_bits(step - l1 - dw_l2, 53)
        split_error = abs(l1 + mp.mpf(dw_l2) + mp.mpf(dw_l3) - step)
        assert split_error <= mp.mpf(2)**-128, split_error
        taylor = []
        for k in range(8):
            exact = 1 / mp.factorial(k)
            high = rn_bits(exact, 53)
            low = rn_bits(exact-high, 53) if exact != high else 0.0
            assert abs(high+mp.mpf(low)-exact) <= exact*mp.mpf(2)**-105
            taylor.append((to_bits(high), to_bits(low)))
        table = []
        for j in range(1024):
            exact = mp.exp(j * step)
            high = rn_bits(exact, 53)
            low = rn_bits(exact-high, 53) if exact != high else 0.0
            assert abs(high+mp.mpf(low)-exact) <= mp.mpf(2)**-104
            table.append((to_bits(high), to_bits(low)))
    rust = ['// Generated by generators/fast_exp_constants.py at 600 bits; do not edit.']
    for name, value in [('INV', inv), ('L1', l1), ('L2D', l2d), ('C2', c2),
                        ('STEP', step_word), ('C1', c1)]:
        rust.append(f'pub(super) const {name}: f64 = f64::from_bits(0x{to_bits(value):016x});')
    rust += ['// Bias cancels the raw reduction index before exponent-field scaling.',
             'pub(super) static HIGH: [u64; 1024] = [']
    rust += [f'    0x{(high-(j << 42)) % (1 << 64):016x},' for j, (high, _) in enumerate(table)]
    rust += ['];', '']
    coq = '''(** Generated by generators/fast_exp_constants.py; do not edit. *)
From Coq Require Import Reals ZArith List Lia Lra.
From Flocq Require Import Core IEEE754.Binary IEEE754.Bits.
From Binary64 Require Import IEEE64 Grid Encodings.
From Interval Require Import Tactic.
Require Import TableCheck.
Import ListNotations.
Open Scope R_scope.
'''
    for name, value in [('fx_inv', inv), ('fx_l1', l1), ('fx_l2d', l2d), ('fx_c2', c2),
                        ('fx_step', step_word), ('fx_c1', c1)]:
        coq += coq_constant(name, value)
    coq += '''Theorem fx_inv_close : Rabs(B fx_inv-1024/ln 2)<=/2^41.
Proof. rewrite fx_inv_val. interval with(i_prec 100). Qed.
Theorem fx_l_split_d : Rabs(B fx_l1+B fx_l2d-ln 2/1024)<=/2^99.
Proof. rewrite fx_l1_val,fx_l2d_val. interval with(i_prec 160). Qed.
Theorem fx_step_close : Rabs(B fx_step-ln 2/1024)<=/2^64.
Proof. rewrite fx_step_val. interval with(i_prec 160). Qed.
Definition fx_t_bits : list (Z * Z) := [
'''
    coq += ';\n'.join(f'  ({high}%Z, {low}%Z)' for high, low in table)
    coq += '''
].
Definition fx_t_hi j : f64 := b64_of_bits(fst(nth j fx_t_bits (0%Z,0%Z))).
Definition fx_t_lo j : f64 := b64_of_bits(snd(nth j fx_t_bits (0%Z,0%Z))).
Lemma fx_t_check : table_check 10 104 fx_t_bits=true.
Proof. vm_compute. reflexivity. Qed.
Theorem fx_t_ok j : (j<1024)%nat ->
 entry_ok (fst(nth j fx_t_bits (0%Z,0%Z))) (snd(nth j fx_t_bits (0%Z,0%Z)))
   (exp(INR j*ln 2/1024)) 104.
Proof. intros H. exact(table_check_ok 10 104 fx_t_bits j fx_t_check H). Qed.
'''
    # The double-word exponential's thresholds: exact binary64 values, shared by
    # the Rust kernel and its Coq transcription.
    dw_thresholds = [('SHIFTER', 6755399441055744.0), ('LIMIT', 1455.0), ('TINY', 2.0**-60),
                     ('LOW_FLOOR', 1.0e-300), ('R_FLOOR', 1.0e-271), ('V_FLOOR', 1.0e-60)]
    dw = ['// Generated by generators/fast_exp_constants.py at 600 bits; do not edit.',
          '// The double-word exponential reuses the bounded exp\'s 1024-way table, whose',
          '// double-word entries formal/fast/FastExpTables.v checks against exp.']
    for name, value in [('INV', inv), ('L1', l1), ('L2', dw_l2), ('L3', dw_l3)] + dw_thresholds:
        dw.append(f'pub(super) const {name}: f64 = f64::from_bits(0x{to_bits(value):016x});')
    dw.append('/// `1/k!` for `k = 0..=7` as (high, low) words.')
    dw.append('pub(super) const TAYLOR: [[u64; 2]; 8] = [')
    dw += [f'    [0x{high:016x}, 0x{low:016x}],' for high, low in taylor]
    dw += ['];', '/// `exp(j*ln(2)/1024)` for `j = 0..1024` as (high, low) words.',
           'pub(super) static TABLE: [[u64; 2]; 1024] = [']
    dw += [f'    [0x{high:016x}, 0x{low:016x}],' for high, low in table]
    dw += ['];', '']
    dwc = '''(** Generated by generators/fast_exp_constants.py; do not edit.
    Constants of the double-word exponential (crates/morphiq-numerics/src/double_word/exp.rs). *)
From Coq Require Import Reals ZArith Lia Lra.
From Flocq Require Import Core IEEE754.Binary IEEE754.Bits.
From Binary64 Require Import IEEE64 Grid Encodings.
From Interval Require Import Tactic.
Require Import FastExpTables.
Open Scope R_scope.
Lemma dwx_bpow_m (k : nat) : bpow radix2 (- Z.of_nat k) = / 2 ^ k.
Proof. rewrite bpow_opp, bpow_powerRZ, <- pow_powerRZ. reflexivity. Qed.
'''
    for name, value in [('dwx_l2', dw_l2), ('dwx_l3', dw_l3)] + [(f'dwx_{n.lower()}', v) for n, v in dw_thresholds]:
        dwc += coq_constant(name, value)
    def coq_word(name, value):
        if value == 0.0:
            return f'''Definition {name} : f64 := b64_of_bits 0.
Lemma {name}_val : B {name} = 0.
Proof. reflexivity. Qed.
Lemma {name}_finite : finite {name}.
Proof. reflexivity. Qed.
'''
        return coq_constant(name, value)

    for k, (high, low) in enumerate(taylor):
        dwc += coq_word(f'dwx_c{k}_hi', struct.unpack('<d', struct.pack('<Q', high))[0])
        dwc += coq_word(f'dwx_c{k}_lo', struct.unpack('<d', struct.pack('<Q', low))[0])
    m2 = int(mp.mpf(dw_l2) * mp.mpf(2)**int(-mp.floor(mp.log(abs(dw_l2), 2)) + 30))
    e2 = -int(-mp.floor(mp.log(abs(dw_l2), 2)) + 30)
    assert mp.mpf(m2) * mp.mpf(2)**e2 == mp.mpf(dw_l2) and abs(m2) < 2**31
    dwc += f'''Lemma dwx_l2_eq : B dwx_l2 = IZR ({m2}) * bpow radix2 ({e2}).
Proof. rewrite dwx_l2_val. change ({e2})%Z with (- Z.of_nat {-e2})%Z. rewrite dwx_bpow_m. field. Qed.
Theorem dwx_split : Rabs (B fx_l1 + B dwx_l2 + B dwx_l3 - ln 2 / 1024) <= / 2 ^ 128.
Proof. rewrite fx_l1_val, dwx_l2_val, dwx_l3_val. interval with (i_prec 300). Qed.
'''
    for k in range(8):
        fact = 1
        for i in range(2, k + 1):
            fact *= i
        dwc += f'''Theorem dwx_c{k}_close : Rabs (B dwx_c{k}_hi + B dwx_c{k}_lo - / {fact}) <= / {fact} * / 2 ^ 105.
Proof. rewrite dwx_c{k}_hi_val, dwx_c{k}_lo_val. interval with (i_prec 300). Qed.
'''
    return {
        ROOT/'formal/fast/DwExpConstants.v': dwc,
        ROOT/'crates/morphiq-numerics/src/double_word/exp_tables.rs': '\n'.join(dw),
        ROOT/'crates/morphiq-numerics/src/exp/bounded_tables.rs': '\n'.join(rust),
        ROOT/'formal/fast/FastExpTables.v': coq,
    }


if __name__ == '__main__':
    for path, text in outputs().items():
        if '--check' in sys.argv:
            if not path.exists() or path.read_text() != text:
                raise SystemExit(f'generated file differs: {path.relative_to(ROOT)}')
        else:
            path.write_text(text)
