#!/usr/bin/env python3
"""Bind erfcx's direct quotient certificates into one real rounding model."""
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
s = '''(** Generated by generators/erfcx_quotient_bounds.py. Each finite branch
    applies a checked Gappa certificate; their intervals cover [2^9,2^897]. *)
From Coq Require Import Reals ZArith Lia Lra Classical.
From Flocq Require Import Core.
Require Import StageGappa ErfcxReciprocal ErfcxEntryTables.
'''
for i in range(28):
    s += f'Require erfcx_tail_quotient_{i:02}.\n'
s += '''Open Scope R_scope.
Definition q_high x := rn (cs_r / rn x).
Definition q_product x := rn (q_high x * rn x).
Definition q_error x := q_high x * rn x - q_product x.
Definition q_residual1 x := rn ((cs_r-q_product x)-q_error x).
Definition q_residual x := rn (q_residual1 x+csl_r).
Definition q_low x := rn (q_residual x/rn x).
Definition quotient_bounds x : Prop :=
 - bpow radix2 (-70) <= ((q_high x+q_low x)-(cs_r+csl_r)/rn x)/((cs_r+csl_r)/rn x) <= bpow radix2 (-70) /\\
 - bpow radix2 (-51) <= q_low x/q_high x <= bpow radix2 (-51) /\\
 bpow radix2 (-899) <= q_high x <= bpow radix2 (-9) /\\
 1/2 <= q_product x <= 5/8 /\\
 - bpow radix2 (-52) <= q_error x <= bpow radix2 (-52) /\\
 - bpow radix2 (-50) <= q_residual1 x <= bpow radix2 (-50) /\\
 - bpow radix2 (-50) <= q_residual x <= bpow radix2 (-50) /\\
 - bpow radix2 (-59) <= q_low x <= bpow radix2 (-59).

Lemma quotient_model x : 512 <= rn x <= bpow radix2 897 -> quotient_bounds x.
Proof.
 intros X.
'''
for i, lower in enumerate(range(9,897,32)):
    upper=min(lower+32,897)
    if i<27:
        s+=f' destruct (Rle_dec (rn x) (bpow radix2 {upper})) as [U{i}|L{i}].\n {{\n'
    else:
        s+=' {\n'
    s+=f''' assert (I : bpow radix2 {lower} <= rn x <= bpow radix2 {upper}) by (bpow_num_all; lra).
 unfold quotient_bounds,q_low,q_residual,q_residual1,q_error,q_product,q_high,cs_r,csl_r.
 repeat split; erfcx_goal (erfcx_tail_quotient_{i:02}.l1 x).
 }}
'''
s+='Qed.\n'
p=ROOT/'formal/erfcx/ErfcxQuotientBounds.v'
if '--check' in sys.argv:
    assert p.read_text()==s,f'{p} differs'
else:
    p.write_text(s)
