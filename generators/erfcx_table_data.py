#!/usr/bin/env python3
"""Transcribe exact erfcx table words and bind their arithmetic certificates.

No new approximation is computed. Coq checks all masked coefficients using
integer decoding, then derives their finiteness, grids and exact differences.
Each Gappa model is connected to the decoded coefficients and IEEE entry.
"""
from pathlib import Path
import struct
import sys

ROOT = Path(__file__).resolve().parents[1]
rows = {}
for line in (ROOT / 'generators/erfcx/tables.out').read_text().splitlines():
    fields = line.split()
    if fields and fields[0] in ('T0', 'T1') and fields[2] in ('A', 'L'):
        key = fields[0], int(fields[1])
        text = fields[4]
        bits = (struct.unpack('>Q', struct.pack('>d', float.fromhex(text)))[0]
                if 'p' in text else int(text, 16))
        rows.setdefault(key, {})[fields[2], int(fields[3])] = bits
assert len(rows) == 177
out = r'''(** Generated by generators/erfcx_table_data.py from exact tables.out words. *)
From Coq Require Import ZArith List Lia Bool.
Require Import ErfcxTableCoefficient.
Import ListNotations.
Open Scope Z_scope.
Definition table_words : list (list Z) := [
'''
for idx, (key, row) in enumerate(sorted(rows.items())):
    values = [row[k, j] for j in range(3) for k in ('A', 'L')]
    values += [row['A', j] for j in range(3, 10)]
    out += ' [' + '; '.join(str(v) for v in values) + ']'
    out += (';' if idx < 176 else '') + f' (* {key[0]} {key[1]} *)\n'
out += r'''].
Definition table_word i k := nth k (nth i table_words []) 0.
Lemma table_words_length : length table_words = 177%nat.
Proof. reflexivity. Qed.
Lemma table_a1_checks : forallb (fun row => coefficient_check (nth 2 row 0) 18 35) table_words = true.
Proof. vm_compute. reflexivity. Qed.
Lemma table_a2_checks : forallb (fun row => coefficient_check (nth 4 row 0) 36 17) table_words = true.
Proof. vm_compute. reflexivity. Qed.
Lemma table_a1_check i : (i<177)%nat -> coefficient_check (table_word i 2) 18 35 = true.
Proof.
 intros I. pose proof table_a1_checks as A.
 apply forallb_forall with (x:=nth i table_words []) in A.
 - exact A.
 - apply nth_In. rewrite table_words_length. exact I.
Qed.
Lemma table_a2_check i : (i<177)%nat -> coefficient_check (table_word i 4) 36 17 = true.
Proof.
 intros I. pose proof table_a2_checks as A.
 apply forallb_forall with (x:=nth i table_words []) in A.
 - exact A.
 - apply nth_In. rewrite table_words_length. exact I.
Qed.
Lemma table_low_checks : forallb (fun row => low_word_check (nth 3 row 0) && low_word_check (nth 5 row 0)) table_words = true.
Proof. vm_compute. reflexivity. Qed.
Lemma table_low_check i : (i<177)%nat -> low_word_check (table_word i 3)=true /\ low_word_check (table_word i 5)=true.
Proof.
 intros I. pose proof table_low_checks as A.
 apply forallb_forall with (x:=nth i table_words []) in A.
 - apply andb_true_iff in A. exact A.
 - apply nth_In. rewrite table_words_length. exact I.
Qed.

Lemma table_word_checks : forallb (fun row =>
 (length row =? 13)%nat && forallb (fun b => word_range_check b ((-4)%Z,0%Z) (4%Z,0%Z)) row) table_words=true.
Proof. vm_compute. reflexivity. Qed.
Lemma table_word_check i k : (i<177)%nat -> (k<13)%nat ->
 word_range_check (table_word i k) ((-4)%Z,0%Z) (4%Z,0%Z)=true.
Proof.
 intros I K. pose proof table_word_checks as C.
 apply forallb_forall with (x:=nth i table_words []) in C.
 - apply andb_true_iff in C as [Length Words]. apply Nat.eqb_eq in Length.
   apply forallb_forall with (x:=table_word i k) in Words;[exact Words|].
   apply nth_In. rewrite Length;exact K.
 - apply nth_In. rewrite table_words_length;exact I.
Qed.
Lemma table_constant_checks : forallb (fun row =>
 word_range_check (nth 0 row 0) (9%Z,(-8)%Z) (2%Z,0%Z) &&
 word_range_check (nth 1 row 0) ((-1)%Z,(-52)%Z) (1%Z,(-52)%Z)) table_words=true.
Proof. vm_compute. reflexivity. Qed.
Lemma table_constant_check i : (i<177)%nat ->
 word_range_check (table_word i 0) (9%Z,(-8)%Z) (2%Z,0%Z)=true /\
 word_range_check (table_word i 1) ((-1)%Z,(-52)%Z) (1%Z,(-52)%Z)=true.
Proof.
 intros I. pose proof table_constant_checks as C.
 apply forallb_forall with (x:=nth i table_words []) in C.
 - apply andb_true_iff in C;exact C.
 - apply nth_In. rewrite table_words_length;exact I.
Qed.
Lemma table_leading_size_checks : forallb (fun row =>
 coefficient_size_check (nth 0 row 0) (nth 2 row 0) (nth 3 row 0) 18 1 (-32) &&
 coefficient_size_check (nth 0 row 0) (nth 4 row 0) (nth 5 row 0) 36 2 (-14)) table_words=true.
Proof. vm_compute. reflexivity. Qed.
Lemma table_leading_size_check i : (i<177)%nat ->
 coefficient_size_check (table_word i 0) (table_word i 2) (table_word i 3) 18 1 (-32)=true /\
 coefficient_size_check (table_word i 0) (table_word i 4) (table_word i 5) 36 2 (-14)=true.
Proof.
 intros I. pose proof table_leading_size_checks as C.
 apply forallb_forall with (x:=nth i table_words []) in C.
 - apply andb_true_iff in C;exact C.
 - apply nth_In. rewrite table_words_length;exact I.
Qed.
'''
dest = ROOT / 'formal/erfcx/ErfcxTableData.v'
if '--check' in sys.argv:
    assert dest.read_text() == out, f'{dest} differs'
else:
    dest.write_text(out)


# Bind each Gappa arithmetic certificate to the same decoded table words.
# The normalized integer/exponent spelling equals Gappa's exact Float2
# constants; Coq checks each equality using word_value_ok.
cert = '''(** Generated by generators/erfcx_table_data.py: table arithmetic certificates. *)
From Coq Require Import Reals ZArith Lia Lra List Classical.
From Flocq Require Import Core IEEE754.Binary IEEE754.Bits.
From Binary64 Require Import IEEE64 Binary64Add.
From Gappa Require Import Gappa_library.
Require Import StageGappa ErfcxTableEntry ErfcxTableEvaluation ErfcxTableCertificateModel.
Import ListNotations.
Open Scope R_scope.
'''
for family, index in sorted(rows):
    cert += f'Require erfcx_{family}_{index:03d}.\n'
for idx, (key, row) in enumerate(sorted(rows.items())):
    values = [row[k, j] for j in range(3) for k in ('A', 'L')]
    values += [row['A', j] for j in range(3, 10)]
    terms = [(f'coef {idx} {k}', b) for k, b in enumerate(values)]
    terms += [(f'cut1 {idx}', values[2] & ~((1 << 18) - 1)),
              (f'cut2 {idx}', values[4] & ~((1 << 36) - 1))]
    equations = []
    for term, bits in terms:
        numerator, denominator = struct.unpack('>d', struct.pack('>Q', bits))[0].as_integer_ratio()
        exponent = -(denominator.bit_length() - 1)
        constant = (f'Float1 ({numerator})' if exponent == 0 else
                    f'float2R (Float2 ({numerator}) ({exponent}))')
        equations.append(f'B ({term})={constant}')
    cert += f'\nLemma row_{idx:03d}_words :\n ' + ' /\\\n '.join(equations) + '.\n'
    cert += 'Proof. repeat split;first [apply word_integer_ok|apply word_value_ok];vm_compute;reflexivity. Qed.\n'
    e = 0 if key[0] == 'T0' else key[1] // 32
    cert += f'''Lemma row_{idx:03d}_bound hx : -/{1 << (6-e)}<=hx<=/{1 << (6-e)} ->
 -/2^67<=(table_polynomial_value {idx} (rn hx) {e}-table_polynomial_exact {idx} (rn hx))/table_polynomial_exact {idx} (rn hx)<=/2^67.
Proof.
 intros H.
 destruct row_{idx:03d}_words as '''
    cert += '[C0 ' + ''.join(f'[C{k} ' for k in range(1, 14)) + 'C14' + ']' * 14 + '.\n'
    cert += ''' unfold table_polynomial_value,table_polynomial_exact,table_rest_value,table_sum_value,tail_coefs.
 cbn [seq map horner_value polynomial_tail].
 rewrite ''' + ','.join(f'C{k}' for k in range(15)) + '.\n'
    cert += f' apply NNPP;intro Hn;apply (erfcx_{key[0]}_{key[1]:03d}.l1 hx);gappa_hyps.\n'
    cert += ''' intro Hb. apply bnd_to in Hb. apply Hn. split.
 - eapply Rle_trans;[|exact (proj1 Hb)]. bpow_num;simpl;lra.
 - apply Rle_trans with (1:=proj2 Hb). bpow_num;simpl;lra.
Qed.
'''
cert += '''
Theorem table_certificate_rn i hx : (i<177)%nat ->
 Rabs hx<=bpow radix2 (table_exponent i-6) ->
 -/2^67<=(table_polynomial_value i (rn hx) (table_exponent i)-table_polynomial_exact i (rn hx))/table_polynomial_exact i (rn hx)<=/2^67.
Proof.
 intros I H. apply Rabs_le_inv in H.
'''
for idx in range(177):
    cert += f' destruct i as [|i];[exact (row_{idx:03d}_bound hx H)|].\n'
cert += ''' lia.
Qed.
Theorem table_certificate i h : (i<177)%nat -> fmtF h ->
 Rabs h<=bpow radix2 (table_exponent i-6) ->
 -/2^67<=(table_polynomial_value i h (table_exponent i)-table_polynomial_exact i h)/table_polynomial_exact i h<=/2^67.
Proof.
 intros I F H. pose proof (table_certificate_rn i h I H) as C.
 assert (R : rn h=h) by (apply round_generic;[exact _|exact F]).
 rewrite R in C;exact C.
Qed.
'''
dest = ROOT / 'formal/erfcx/ErfcxTableCertificates.v'
if '--check' in sys.argv:
    assert dest.read_text() == cert, f'{dest} differs'
else:
    dest.write_text(cert)
