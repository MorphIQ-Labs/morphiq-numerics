#!/usr/bin/env python3
"""Exact rational brackets for Payne-Hanek's binary64 exponent range.

The generated Coq file checks determinant, denominator coverage and integer
residual bounds for every exponent. Python's search is not a trusted oracle:
TrigSeparation proves the checker sufficient, using the certified 2/pi bits.
"""
from fractions import Fraction
from pathlib import Path
import sys

from trig_reduction import derive

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'formal/trig/TrigSeparationData.v'


def bracket(numerator, denominator, limit):
    """Adjacent Farey fractions bracketing a rational at bounded denominator."""
    a, b, c, d = 0, 1, 1, 0
    n, den = numerator, denominator
    while den:
        quotient = n // den
        if b + quotient * d > limit:
            break
        a, c = c, a + quotient * c
        b, d = d, b + quotient * d
        n, den = den, n - quotient * den
    if not den:
        raise ValueError('table rational has an exact small-denominator representation')
    weight = (limit - b) // d
    return sorted([(a + weight * c, b + weight * d), (c, d)],
                  key=lambda pair: Fraction(*pair))


def generate():
    derived = derive()
    bits = 64 * derived['words']
    table = derived['table']
    limit = (1 << 53) - 1
    rows = []
    # The extra exponent covers 2*x at the largest binary64 binade,
    # needed to separate quadrant decisions from half-integer boundaries.
    for exponent in range(-53, 973):
        scale = 1 << (bits - exponent)
        integer, remainder = divmod(table, scale)
        (pl, ql), (ph, qh) = bracket(remainder, scale, limit)
        row = f'  lifted_witness ({exponent})%Z {pl}%Z {ql}%Z {ph}%Z {qh}%Z'
        pl += integer * ql
        ph += integer * qh
        # These checks are also proved by computation in the generated Coq
        # file, then interpreted by the generic separation theorem.
        assert ql > 0 and qh > 0 and ql * ph - qh * pl == 1
        assert ql + qh >= 1 << 53
        assert ((ql * table - pl * scale) << 62) >= scale
        assert ((ph * scale - qh * (table + 1)) << 62) >= scale
        rows.append(row)
    return '''(** Exact rational witnesses for E=-53,...,972, in that order.
    Generated by generators/trig_separation.py; do not edit. The executable
    checker and its sufficiency theorem live in TrigSeparation.v. *)
From Coq Require Import ZArith List.
Require Import TrigConstants TrigSeparation.
Import ListNotations.

(** Store the small fractional numerators. This computation restores the
    common integer part before the checker validates the full witnesses. *)
Definition lifted_witness (e pl ql ph qh : Z) : separation_witness :=
  let whole := Z.shiftr trig_two_over_pi (1408-e) in
  witness (whole*ql+pl)%Z ql (whole*qh+ph)%Z qh.

Definition trig_separation_witnesses : list separation_witness := [
''' + ';\n'.join(rows) + '''].

Lemma trig_separation_count : length trig_separation_witnesses=1026%nat.
Proof. reflexivity. Qed.

Theorem trig_separation_checked :
  separation_check_from (-53)%Z trig_separation_witnesses=true.
Proof. vm_compute; reflexivity. Qed.
'''


def main():
    data = generate()
    if '--check' in sys.argv[1:]:
        if OUTPUT.read_text() != data:
            sys.exit(f'{OUTPUT} differs from a fresh generation')
    else:
        OUTPUT.write_text(data)


if __name__ == '__main__':
    main()
