#!/usr/bin/env python3
"""Transcribe the generated erfcx middle-tail constants into Coq encodings.

This does not approximate new constants: it decodes tables.out's exact binary64
words. Coq proves each word's finiteness, dyadic value and magnitude bound.
"""
from fractions import Fraction
from pathlib import Path
import struct
import sys

ROOT = Path(__file__).resolve().parents[1]
words = {}
for line in (ROOT / 'generators/erfcx/tables.out').read_text().splitlines():
    fields = line.split()
    if fields[0] == 'PA':
        words['pa' + fields[1]] = int(fields[2], 16)
    elif fields[0] in ('CS', 'CSL'):
        words[fields[0].lower()] = int(fields[1], 16)
words.update(half=0x3fe0000000000000, neg_half=0xbfe0000000000000)
out = '''(** Generated by generators/erfcx_entry_tables.py from tables.out. *)
From Coq Require Import Reals ZArith Lia Lra.
From Flocq Require Import Core IEEE754.Binary IEEE754.Bits.
From Binary64 Require Import IEEE64 Encodings.
From Gappa Require Import Gappa_library.
Require Import StageGappa.
Open Scope R_scope.
'''
for name, bits in words.items():
    value = struct.unpack('>d', bits.to_bytes(8, 'big'))[0]
    num, den = Fraction(value).as_integer_ratio()
    exp = -(den.bit_length() - 1)
    mantissa = (bits & ((1 << 52) - 1)) | (1 << 52)
    raw_exp = ((bits >> 52) & 2047) - 1075
    sign = 'true' if bits >> 63 else 'false'
    out += f'''
Definition {name} : f64 := b64_of_bits {bits}.
Definition {name}_r : R := float2R (Float2 ({num}) ({exp})).
Lemma {name}_ok : finite {name} /\\ B {name} = {name}_r /\\ Rabs {name}_r <= 65536.
Proof.
 split.
 - exact (bits_finite {bits} {sign} {mantissa} ({raw_exp}) eq_refl).
 - split.
   + pose proof (bits_val {bits} {sign} {mantissa} {-raw_exp} eq_refl) as V.
     unfold {name}, {name}_r, float2R, F2R. cbn [Fnum Fexp]. rewrite V. simpl. bpow_num. field.
   + unfold {name}_r, float2R, F2R. cbn [Fnum Fexp]. simpl. bpow_num. apply Rabs_le; split; lra.
Qed.
'''
dest = ROOT / 'formal/erfcx/ErfcxEntryTables.v'
if '--check' in sys.argv:
    assert dest.read_text() == out, f'{dest} differs'
else:
    dest.write_text(out)
