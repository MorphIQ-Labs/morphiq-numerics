#!/usr/bin/env python3
"""Bind the private normal-pair reconstruction to the existing ln coefficients.

No new coefficients are fitted. Gappa proves the difference between the two
binary64 sequences on the reduction bounds established by FastRandomLog.v.
The fixed 2^-45 goal is the predeclared composition budget, not a sampled error.
"""
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]


def output():
    coefficients = dict(line.split() for line in
                        (ROOT / 'generators/ln_poly.out').read_text().splitlines()
                        if line.strip())
    return fr'''# Generated by generators/fast_random_radius.py.
# Radius-specific reconstruction versus the compensated logarithm.
@rnd = float<ieee_64, ne>;
z = rnd(zz);
hi = rnd(hh);
lo = rnd(ll);
h3 = {coefficients["h3"]};
h4 = {coefficients["h4"]};
h5 = {coefficients["h5"]};
h6 = {coefficients["h6"]};
z2 = rnd(z*z);
t0 = rnd(rnd(z*h3)-1b-1);
t1 = rnd(rnd(z*h5)+h4);
a1 = rnd(rnd(z2*h6)+t1);
q6 = rnd(z2*rnd(rnd(z2*a1)+t0));
q4 = rnd(z2*rnd(t0+rnd(z2*h4)));
s = rnd(hi+z);
e1 = rnd(z-rnd(s-hi));
old = rnd(s+rnd(rnd(e1+lo)+q6));
new = rnd(s+rnd(lo+q4));
{{ zz in [-1b-9,1b-9] /\ hh in [-38,38] /\ ll in [-1b-38,1b-38]
  -> new-old in [-1b-45,1b-45] }}
new-old -> (new-(s+rnd(lo+q4))) - (old-(s+rnd(rnd(e1+lo)+q6))) + (rnd(lo+q4)-(lo+q4)) - (rnd(rnd(e1+lo)+q6)-(rnd(e1+lo)+q6)) - (rnd(e1+lo)-(e1+lo)) + (q4-q6)-e1;
e1 -> (e1-(z-rnd(s-hi))) - (rnd(s-hi)-(s-hi)) - (s-(hi+z));
q4-q6 -> (q4-z2*rnd(t0+rnd(z2*h4))) - (q6-z2*rnd(rnd(z2*a1)+t0)) + z2*((rnd(t0+rnd(z2*h4))-(t0+rnd(z2*h4)))-(rnd(rnd(z2*a1)+t0)-(rnd(z2*a1)+t0))+(rnd(z2*h4)-z2*h4)-(rnd(z2*a1)-z2*a1)+z2*(h4-a1));
h4-a1 -> -(a1-(rnd(z2*h6)+t1)) - (t1-(rnd(z*h5)+h4)) - rnd(z2*h6) - rnd(z*h5);
'''


def main():
    path = ROOT / 'formal/normal/normal_pair_log.g'
    text = output()
    if '--check' in sys.argv:
        if path.read_text() != text:
            sys.exit(f'{path} differs from a fresh generation')
    else:
        path.write_text(text)


if __name__ == '__main__':
    main()
