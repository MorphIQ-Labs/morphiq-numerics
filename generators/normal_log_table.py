#!/usr/bin/env python3
"""Generate the near far-tail log-CDF correction table at 600 and 1000 bits.

Each row is the degree-seven Taylor polynomial of
  log(a) + log(2*pi)/2 + P(1/a^2),
where P is the exact eight-term logarithmic Mills polynomial already derived
in normal_constants.py. Centers are 37.5, 38.5, ..., 63.5. Coq checks the
rounded polynomial's uniform approximation error on each half-unit interval.
No external approximation coefficients are used.
"""
from pathlib import Path
import struct
import subprocess
import mpmath as mp
from normal_constants import log_tail_coefficients

ROOT = Path(__file__).resolve().parents[1]

def rows(precision):
    with mp.workprec(precision):
        coefficients = [mp.mpf(c.numerator) / c.denominator
                        for c in log_tail_coefficients()]
        def correction(a):
            u = 1 / (a*a)
            return mp.log(a) + mp.log(2*mp.pi)/2 + sum(
                c*u**(i+1) for i, c in enumerate(coefficients))
        return [[float(c) for c in mp.taylor(correction, mp.mpf(75+2*i)/2, 7)]
                for i in range(27)]

def word(value):
    return struct.unpack('>Q', struct.pack('>d', value))[0]

def rational(value):
    n, d = value.as_integer_ratio()
    return f'({n}/{d})'

def horner(row):
    result = rational(row[-1])
    for c in reversed(row[:-1]):
        result = f'({rational(c)}+h*{result})'
    return result


def row_proofs(table):
    text = '''(** Generated by generators/normal_log_table.py. *)
From Coq Require Import Reals ZArith Lia Lra.
From Flocq Require Import Core IEEE754.Bits.
From Binary64 Require Import IEEE64 Encodings.
From Interval Require Import Tactic.
Require Import StageGappa NormalLogTailApprox NormalLogTableApprox NormalLogTableEvaluation.
Open Scope R_scope.
'''
    for i, row in enumerate(table):
        prefix = f'log_table_{i:02}'
        for j, value in enumerate(row):
            n = word(value)
            exponent = ((n >> 52) & 2047) - 1075
            mantissa = (n & ((1 << 52) - 1)) + (1 << 52)
            sign = str(value < 0).lower()
            text += f'''Definition {prefix}_c{j} := b64_of_bits {n}.
Definition {prefix}_r{j} : R := {rational(value)}.
Lemma {prefix}_c{j}_ok : finite {prefix}_c{j} /\\ B {prefix}_c{j}={prefix}_r{j}.
Proof.
 split;[exact(bits_finite {n} {sign} {mantissa} ({exponent}) eq_refl)|].
 unfold {prefix}_c{j},{prefix}_r{j}.
 rewrite(bits_val {n} {sign} {mantissa} {-exponent} eq_refl);simpl;field.
Qed.
'''
        args = ' '.join(f'{prefix}_c{j}' for j in range(8))
        reals = ' '.join(f'{prefix}_r{j}' for j in range(8))
        text += f'''Definition {prefix}_value64 d := log_table_horner64 d {args}.
Lemma {prefix}_words d : finite d -> Rabs(B d)<=/2 ->
 finite({prefix}_value64 d) /\\ 3<=B({prefix}_value64 d)<=7 /\\
 Rabs(B({prefix}_value64 d)-(ln({75+2*i}/2+B d)+ln(2*PI)/2+
 normal_log_tail_polynomial(/(({75+2*i}/2+B d)*({75+2*i}/2+B d)))))<=21*bpow radix2(-54).
Proof.
 intros Fd D;assert(Domain : -1/2<=B d<=1/2)by(apply Rabs_le_inv in D;lra).
'''
        for j in range(8):
            text += f' destruct {prefix}_c{j}_ok as[F{j} V{j}].\n'
        text += f' destruct(log_table_horner_ieee d {args} Fd D\n'
        for j in range(8):
            text += f' F{j} ltac:(rewrite V{j};unfold {prefix}_r{j};interval with(i_prec 100))\n'
        text += ')as[F [Value Range]];cbv zeta in F,Value,Range.\n'
        text += ' rewrite '+','.join(f'V{j}' for j in range(8))+' in Value.\n'
        text += f' destruct(log_table_model (B d) {reals} Domain\n'
        for j in range(8):
            text += f' ltac:(unfold {prefix}_r{j};split;interval with(i_prec 100))\n'
        text += ')as[Eval Bound].\n rewrite <-Value in Eval,Bound.\n'
        text += f''' assert(Exact : log_table_exact (B d) {reals}=normal_log_table_poly_{i:02}(B d))by reflexivity.
 rewrite Exact in Eval.
 pose proof(normal_log_table_approx_{i:02}(B d)Domain)as Approx.
 unfold {prefix}_value64;split;[exact F|];split;[exact Bound|].
 apply Rabs_le_inv in Eval,Approx;apply Rabs_le;bpow_num_all;split;lra.
Qed.
'''
    return text

def generate():
    table = rows(600)
    assert table == rows(1000), 'coefficients must stabilize at both precisions'
    rust = ROOT / 'crates/morphiq-numerics/src/normal_distribution/log_first_table.rs'
    rust.write_text('// Generated by generators/normal_log_table.py at 600 and 1000 bits.\n'
                    'pub(super) const C: [[f64; 8]; 27] = [\n' + ''.join(
                        '    [' + ','.join(f'f64::from_bits(0x{word(c):016x})' for c in row)
                        + '],\n' for row in table) + '];\n')
    subprocess.run(['rustfmt', '--edition', '2024', str(rust)], check=True)
    coq = '''(** Generated by generators/normal_log_table.py. Rounded Taylor
    coefficients; each continuum bound is checked in Coq's kernel. *)
From Coq Require Import Reals ZArith Lia Lra.
From Flocq Require Import Core.
From Interval Require Import Tactic.
Require Import StageGappa NormalLogTailApprox.
Open Scope R_scope.
'''
    for i, row in enumerate(table):
        coq += f'''
Definition normal_log_table_poly_{i:02} h := {horner(row)}.
Lemma normal_log_table_approx_{i:02} h : -1/2<=h<=1/2 ->
 Rabs(normal_log_table_poly_{i:02} h-
 (ln({75+2*i}/2+h)+ln(2*PI)/2+
 normal_log_tail_polynomial(/(({75+2*i}/2+h)*({75+2*i}/2+h)))))<=3*bpow radix2(-52).
Proof.
 intros H;unfold normal_log_table_poly_{i:02},normal_log_tail_polynomial;
 apply Rabs_le;split;
 interval with(i_taylor h,i_degree 10,i_bisect h,i_prec 160,i_depth 8).
Qed.
'''
    (ROOT / 'formal/normal/NormalLogTableApprox.v').write_text(coq)
    (ROOT / 'formal/normal/NormalLogTableRows.v').write_text(row_proofs(table))
    sollya = "// Generated by generators/normal_log_table.py.\nprec = 300;\ndisplay = hexadecimal;\n"
    mills = [f"({c.numerator}/{c.denominator})" for c in log_tail_coefficients()]
    for i, row in enumerate(table):
        u = f"(1/(({75+2*i}/2+x)^2))"
        correction = mills[-1]
        for c in reversed(mills[:-1]):
            correction = f"({c}+{u}*{correction})"
        target = f"log({75+2*i}/2+x)+log(2*pi)/2+{u}*{correction}"
        poly = horner(row).replace('h', 'x')
        sollya += f'err{i} = supnorm({poly}, {target}, [-1/2;1/2], absolute, 2^-30);\nprint("t{i}", sup(err{i}));\n'
    (ROOT / 'generators/normal_log_table_poly.sollya').write_text(sollya)


if __name__ == '__main__':
    generate()
