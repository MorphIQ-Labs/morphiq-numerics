#!/usr/bin/env python3
"""Generate the fixed-coefficient normal CDF far tail from its defining integral.

mpmath 1.4.1, 220 bits. Fit M(t)=a*Phi(-a)/phi(a), a=1/sqrt(t), on
4/2025 <= t <= 1/64 with degree 10, then round coefficients to binary64.
The fit is only a construction: Coq checks the rounded polynomial's ODE residual
and its Gaussian-integral anchor at y=16; Gappa checks the exact Estrin schedule.
No external implementation coefficients are used. Usage: [--check].
"""
from pathlib import Path
from fractions import Fraction
import sys
import mpmath as mp
from fast_cdf_constants import coq_constant, word

ROOT = Path(__file__).resolve().parents[1]
mp.mp.prec = 220


def arithmetic():
    """Transcribe the fixed operation graph and prove each binary64 operation finite."""
    constants = {f'c{i}': f'cdf_far_p{i}' for i in range(11)}
    constants['scale'] = 'cdf_far_scale'
    caps = dict(zip([f'c{i}' for i in range(11)], [0, 0, 2, 4, 7, 10, 14, 17, 21, 25, 27]))
    caps.update(scale=0, v=-3)
    nodes = [('t', '*', 'v', 'v'), ('t2', '*', 't', 't'), ('t4', '*', 't2', 't2')]
    for i in range(5):
        nodes += [(f'm{i}', '*', 't', f'c{2*i+1}'), (f'p{i}', '+', f'c{2*i}', f'm{i}')]
    nodes += [('q0', '*', 't2', 'p1'), ('b0', '+', 'p0', 'q0'),
              ('q1', '*', 't2', 'p3'), ('b1', '+', 'p2', 'q1'),
              ('q2', '*', 't2', 'c10'), ('b2', '+', 'p4', 'q2'),
              ('q3', '*', 't4', 'b1'), ('b3', '+', 'b0', 'q3'),
              ('t8', '*', 't4', 't4'), ('q4', '*', 't8', 'b2'),
              ('p', '+', 'b3', 'q4'), ('s', '*', 'v', 'scale'), ('r', '*', 's', 'p')]
    header = '''(** Generated by generators/fast_cdf_far_constants.py; do not edit. *)
From Coq Require Import Reals ZArith Lia Lra Classical.
From Flocq Require Import Core IEEE754.Binary IEEE754.Bits.
From Binary64 Require Import Binary64Add IEEE64 IEEE64Add IEEE64Mul RoundingGaps.
From Gappa Require Import Gappa_library.
From Interval Require Import Tactic.
Require Import StageGappa ErfcxReciprocal ErfcxTableEvaluation FastCdfFarConstants.
Require normal_fast_cdf_far.
Open Scope R_scope.
Ltac far_bound :=
 first [match goal with
 | H : Rabs ?a <= ?u |- Rabs (?a * ?a) <= ?cap =>
     rewrite Rabs_mult; apply Rle_trans with (u*u);
     [apply Rmult_le_compat; [apply Rabs_pos|apply Rabs_pos|exact H|exact H]|lra]
 end | table_bound].
Ltac far_op op k e a b F V C :=
 destruct (op k e a b ltac:(assumption) ltac:(assumption)
   ltac:(lia) ltac:(lia) ltac:(reflexivity) ltac:(lia)
   ltac:(unfold bnd;bpow_num;cbn [IZR];far_bound)) as [F [V C]];
 unfold bnd in C;revert C;bpow_num;cbn [IZR];intro C.
'''
    def operand(x, real):
        return ('B ' if real else '') + constants[x] if x in constants else x
    source = header
    for suffix in ('64', '_value', '_ideal'):
        source += f'\nDefinition fast_cdf_far_ratio{suffix} a :=\n'
        real = suffix != '64'
        rounded = suffix == '_value'
        source += ('  let v:=fdiv one a in\n' if not real else
                   '  let v:=rn(1/a) in\n' if rounded else '  let v:=1/a in\n')
        for name,op,left,right in nodes:
            a,b = operand(left,real),operand(right,real)
            expr = f'{a}{op}{b}' if real else f'{"fmul" if op=="*" else "fadd"} {a} {b}'
            if rounded:
                expr = f'rn({expr})'
            source += f'  let {name}:={expr} in\n'
        source += '  r.\n'
    source += r'''
Lemma fast_cdf_far_ratio_ieee a : finite a -> 8<=B a<=45/2 ->
  finite(fast_cdf_far_ratio64 a) /\
  B(fast_cdf_far_ratio64 a)=fast_cdf_far_ratio_value (B a).
Proof.
  intros Fa A. destruct one_ok as [Fone Vone].
'''
    for short,full in constants.items():
        source += f'  pose proof {full}_finite as F{short}.\n'
        source += f'  assert (C{short} : Rabs(B {full})<=bpow radix2({caps[short]})) by (rewrite {full}_val; bpow_num; interval with (i_prec 100)).\n'
        source += f'  revert C{short}; bpow_num; intro C{short}.\n'
    source += r'''  assert (Q : bnd 1 (-3) (B one/B a)).
  { unfold bnd. rewrite Vone,Rmult_1_l. change (bpow radix2(-3)) with (/8).
    rewrite Rabs_pos_eq by (apply Rlt_le,Rdiv_lt_0_compat;lra).
    unfold Rdiv; rewrite Rmult_1_l. apply Rinv_le_contravar;lra. }
  destruct (fdiv_bnd 1 (-3) one a Fone ltac:(lra) ltac:(lia) ltac:(lia)
    ltac:(reflexivity) ltac:(lia) Q) as [Fv [Vv Cv]].
  rewrite Vone in Vv. unfold bnd in Cv; revert Cv; bpow_num; cbn [IZR]; intro Cv.
  set (v:=fdiv one a) in *.
'''
    for name,op,left,right in nodes:
        cap = Fraction(2)**caps[left] * Fraction(2)**caps[right] if op=='*' else Fraction(2)**caps[left]+Fraction(2)**caps[right]
        exponent = -100
        while Fraction(2)**exponent < cap:
            exponent += 1
        caps[name] = exponent
        a,b = operand(left,False),operand(right,False)
        operation = 'fmul' if op=='*' else 'fadd'
        source += f'  far_op {operation}_bnd 1%Z ({exponent})%Z {a} {b} F{name} V{name} C{name}.\n'
        source += f'  set ({name}:={operation} {a} {b}) in *.\n'
    source += '  unfold fast_cdf_far_ratio64. fold v '+' '.join(n[0] for n in nodes)+'.\n'
    source += '  split; [exact Fr|]. rewrite '+','.join('V'+n[0] for n in reversed(nodes))+',Vv. reflexivity.\nQed.\n'
    source += r'''
Lemma fast_cdf_far_ratio_certificate a : F64 a -> 8<=a<=45/2 ->
  REL (fast_cdf_far_ratio_value a) (fast_cdf_far_ratio_ideal a)
    (makepairF (Float2 (-3) (-52)) (Float2 3 (-52))) /\
  (1/64<=fast_cdf_far_ratio_value a<=1/8) /\
  (1/64<=fast_cdf_far_ratio_ideal a<=1/8).
Proof.
  intros F A. assert (Ra : rn a=a) by (apply round_generic; [exact _|exact F]).
  unfold fast_cdf_far_ratio_value,fast_cdf_far_ratio_ideal. cbv zeta.
'''
    source += '  rewrite '+','.join(full+'_g' for full in constants.values())+'.\n'
    source += r'''  rewrite <-Ra. split.
  - apply NNPP. intros Hn. apply (normal_fast_cdf_far.l1 a). gappa_hyps. left. left. exact Hn.
  - repeat split; erfcx_goal (normal_fast_cdf_far.l1 a).
Qed.
'''
    return source


def outputs():
    assert mp.__version__ == '1.4.1'
    def scaled(t):
        a = 1 / mp.sqrt(t)
        return a * mp.sqrt(mp.pi / 2) * mp.exp(a*a/2) * mp.erfc(a/mp.sqrt(2))
    coefficients = [float(c) for c in reversed(mp.chebyfit(scaled, [mp.mpf(4)/2025, mp.mpf(1)/64], 11))]
    scale = float(mp.sqrt(2/mp.pi))
    names = [f'cdf_far_p{i}' for i in range(11)]
    rust = ['//! Generated by generators/fast_cdf_far_constants.py; do not edit.',
            '//! Scaled normal tail in t = 1/a²; ascending powers.',
            'pub(super) const FAR_POLY: [f64; 11] = [']
    rust += [f'    f64::from_bits(0x{word(c):016x}),' for c in coefficients]
    rust += ['];', f'pub(super) const FAR_SCALE: f64 = f64::from_bits(0x{word(scale):016x});', '']
    constants = '''(** Generated by generators/fast_cdf_far_constants.py; do not edit. *)
From Coq Require Import Reals ZArith Lia Lra List.
From Flocq Require Import Core IEEE754.Binary IEEE754.Bits.
From Binary64 Require Import IEEE64 Encodings.
From Gappa Require Import Gappa_library.
Require Import ErfcxTableCertificateModel ErfcxConstants FastCdfConstants.
Import ListNotations.
Open Scope R_scope.
'''
    constants += '\n'.join(coq_constant(n,c) for n,c in zip(names+['cdf_far_scale'],coefficients+[scale]))
    constants += '\nDefinition cdf_far_words := ['+'; '.join('B '+n for n in names)+'].\n'
    constants += '''Definition cdf_far_poly t := cdf_horner cdf_far_words t.
Definition cdf_far_dpoly t := cdf_dhorner cdf_far_words t.
Definition cdf_far_residual t := 2*t*t*cdf_far_dpoly t+(1+t)*cdf_far_poly t-1.
Definition cdf_far_real y := inv_sqrt_pi/y*cdf_far_poly (1/(2*y*y)).
'''
    constants += 'Ltac cdf_far_values := rewrite '+','.join(n+'_val' for n in names)+'.\n'
    residual = '''(** Generated by generators/fast_cdf_far_constants.py; do not edit.
    The interval extends to the right-end Gaussian anchor y=16. *)
From Coq Require Import Reals Lra.
From Interval Require Import Tactic.
Require Import FastCdfConstants FastCdfFarConstants.
Open Scope R_scope.
Theorem cdf_far_residual_bound t : 1/512 <= t <= 1/64 ->
  Rabs(cdf_far_residual t) <= /2^54.
Proof.
  intros T. unfold cdf_far_residual,cdf_far_poly,cdf_far_dpoly,cdf_far_words.
  cbn [cdf_horner cdf_dhorner]. cdf_far_values.
  interval with (i_bisect t, i_taylor t, i_degree 12, i_prec 160, i_depth 12).
Qed.
'''
    # Replay the existing outward-rounded Gaussian series construction at 16.
    precision, degree, cn, cd = 1200, 1100, 16, 1
    unit = 2**precision
    lo = hi = sl = sh = unit
    for k in range(degree):
        n,d = cn*cn*(2*k+1), cd*cd*(k+1)*(2*k+3)
        lo,hi = -(hi*n//d)-1, -(lo*n//d)
        sl,sh = sl+lo,sh+hi
    anchor = f'''(** Generated by generators/fast_cdf_far_constants.py; do not edit. *)
From Coq Require Import Reals ZArith Lia Lra.
From Flocq Require Import Core.
From Interval Require Import Tactic.
Require Import StageGappa ErfcxConstants ErfcxGaussianSeries ErfcxGaussianBox
  ErfcxGaussianTarget ErfcxGaussianRemainder FastCdfConstants FastCdfFarConstants.
Open Scope R_scope.
Definition cdf_far_anchor_box := box ({lo}) ({hi}) ({sl}) ({sh}).
Lemma cdf_far_anchor_box_checked : gaussian_boxes 16 1 (2^1200) 1100=cdf_far_anchor_box.
Proof. vm_compute; reflexivity. Qed.
Theorem cdf_far_anchor_error : Rabs(cdf_far_real 16-gaussian_erfcx 16)
  <= /2^55*gaussian_erfcx 16.
Proof.
  pose proof (proj2(gaussian_boxes_correct 16 1 (2^1200) 1100 ltac:(lia))) as Bound.
  rewrite cdf_far_anchor_box_checked in Bound.
  apply contains_divide in Bound; [|apply Z.pow_pos_nonneg; lia].
  unfold cdf_far_anchor_box in Bound; cbn [sum_lo sum_hi] in Bound.
  replace (IZR 16 / IZR 1) with 16 in Bound by (simpl; field).
  change (({sl})/{unit}<=gaussian_sum 1100 16<=({sh})/{unit}) in Bound.
  assert (A : Rabs(cdf_far_real 16-gaussian_approx 1100 16)<=/2^60).
  {{ unfold cdf_far_real,cdf_far_poly,cdf_far_words,gaussian_approx,inv_sqrt_pi.
     cbn [cdf_horner]. cdf_far_values. interval with (i_prec 1200). }}
  assert (V : 1/30<=gaussian_approx 1100 16<=1/25).
  {{ unfold gaussian_approx,inv_sqrt_pi. split; interval with (i_prec 1200). }}
  pose proof (gaussian_remainder_16 16 ltac:(rewrite Rabs_pos_eq;lra)) as R.
  change (Rabs(gaussian_erfcx 16-gaussian_approx 1100 16)<=bpow radix2(-350)) in R.
  assert (Budget : /2^60+bpow radix2(-350)<=/2^55*(1/30-bpow radix2(-350)))
    by (bpow_num; interval).
  apply Rabs_le_inv in A. apply Rabs_le_inv in R.
  assert (Lower : 1/30-bpow radix2(-350)<=gaussian_erfcx 16) by lra.
  assert (Scale : /2^55*(1/30-bpow radix2(-350))<=/2^55*gaussian_erfcx 16)
    by (apply Rmult_le_compat_l; [interval|exact Lower]).
  apply Rabs_le. lra.
Qed.
'''
    gappa = ['# Generated by generators/fast_cdf_far_constants.py; exact far-tail ratio schedule.', '@rnd = float<ieee_64, ne>;']
    gappa += [f'c{i} = {c.hex()};' for i,c in enumerate(coefficients)]
    gappa += [f'scale = {scale.hex()};', 'a = rnd(aa);',
              'v = rnd(1/a);', 'V = 1/a;',
              't = rnd(v*v);', 'T = V*V;',
              't2 = rnd(t*t);', 'T2 = T*T;',
              't4 = rnd(t2*t2);', 'T4 = T2*T2;']
    for i in range(5):
        gappa += [f'p{i} = rnd(c{2*i}+rnd(t*c{2*i+1}));',f'P{i} = c{2*i}+T*c{2*i+1};']
    gappa += ['b0 = rnd(p0+rnd(t2*p1));', 'B0 = P0+T2*P1;',
              'b1 = rnd(p2+rnd(t2*p3));', 'B1 = P2+T2*P3;',
              'b2 = rnd(p4+rnd(t2*c10));', 'B2 = P4+T2*c10;',
              'p = rnd(rnd(b0+rnd(t4*b1))+rnd(rnd(t4*t4)*b2));',
              'P = (B0+T4*B1)+(T4*T4)*B2;',
              'r = rnd(rnd(v*scale)*p);', 'R = (V*scale)*P;',
              '{ aa in [8, 22.5] -> r -/ R in [-0x1.8p-51, 0x1.8p-51] /\\ r in [0.025, 0.125] /\\ R in [0.025, 0.125] }']
    return {ROOT/'crates/morphiq-numerics/src/fast/cdf_far_tables.rs':'\n'.join(rust),
            ROOT/'formal/fast/FastCdfFarConstants.v':constants,
            ROOT/'formal/fast/FastCdfFarResidual.v':residual,
            ROOT/'formal/fast/FastCdfFarAnchor.v':anchor,
            ROOT/'formal/normal/fast_cdf_far.g':'\n'.join(gappa)+'\n',
            ROOT/'formal/fast/FastCdfFarArithmetic.v':arithmetic()}


def main():
    for path,text in outputs().items():
        if '--check' in sys.argv:
            if not path.exists() or path.read_text()!=text:
                raise SystemExit(f'generated file differs: {path.relative_to(ROOT)}')
        else:
            path.write_text(text)


if __name__=='__main__':
    main()
