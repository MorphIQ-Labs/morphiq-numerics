#!/usr/bin/env python3
"""Arithmetic certificates for bounded kernels, using existing generated words.

No approximation coefficients are fitted here. erfcx/tables.out is the output
of the pinned Sollya generator; Gappa checks every floating-point operation.
"""
from pathlib import Path
import argparse
import struct
import re
import math

ROOT = Path(__file__).resolve().parents[1]


def hexfloat(word):
    return struct.unpack('>d', int(word, 16).to_bytes(8, 'big'))[0].hex()


def erfcx_rows():
    rows = {}
    for line in (ROOT / 'generators/erfcx/tables.out').read_text().splitlines():
        fields = line.split()
        if not fields or fields[0] not in ('T0', 'T1'):
            continue
        key = (fields[0], int(fields[1]))
        row = rows.setdefault(key, {})
        if fields[2] in ('A', 'L'):
            row[fields[2] + fields[3]] = hexfloat(fields[4])
        elif fields[2] == 'HM':
            row['HM'] = hexfloat(fields[3])
    return rows


def certificate(row):
    lines = ['# Generated by generators/fast_certificates.py; paired high-word erfcx.',
             '@rnd = float<ieee_64, ne>;']
    lines += [f'a{i} = {row[f"A{i}"]};' for i in range(10)]
    lines += [f'l{i} = {row[f"L{i}"]};' for i in range(3)]
    lines += ['h = rnd(hx);', 'h2 = rnd(h*h);']
    for i in range(5):
        lines += [f'p{i} = rnd(a{2*i} + rnd(h*a{2*i+1}));',
                  f'q{i} = a{2*i} + h*a{2*i+1};']
    lines += ['y4 = p4;', 'e4 = q4;']
    for i in reversed(range(4)):
        lines += [f'y{i} = rnd(p{i}+rnd(h2*y{i+1}));',
                  f'e{i} = q{i}+h*h*e{i+1};']
    tail = 'a9'
    for i in reversed(range(3, 9)):
        tail = f'a{i}+h*({tail})'
    lines += [f'P = a0+l0+(a1+l1)*h+(a2+l2)*h*h+h*h*h*({tail});',
              f'{{ hx in [-{row["HM"]}, {row["HM"]}] ->',
              '  (y0-P)/P in [-0x1.cp-52, 0x1.cp-52] /\\ y0 in [0x1p-6, 4] }',
              'y0-P -> (y0-e0)-(l0+h*l1+h*h*l2);']
    for i in range(4):
        lines += [f'y{i}-e{i} -> (y{i}-(p{i}+rnd(h2*y{i+1})))',
                  f' + (rnd(h2*y{i+1})-h2*y{i+1}) + (p{i}-q{i})',
                  f' + h2*(y{i+1}-e{i+1})+(h2-h*h)*e{i+1};']
    for i in range(5):
        lines += [f'p{i}-q{i} -> (p{i}-(a{2*i}+rnd(h*a{2*i+1})))',
                  f' + (rnd(h*a{2*i+1})-h*a{2*i+1});']
    return '\n'.join(lines) + '\n'


def coq_certificates(rows):
    lines = ["(** Generated by generators/fast_certificates.py. *)",
             "From Coq Require Import Reals ZArith Lia Lra Classical.",
             "From Flocq Require Import Core IEEE754.Binary IEEE754.Bits.",
             "From Binary64 Require Import IEEE64 Binary64Add RoundingGaps.",
             "From Gappa Require Import Gappa_library.",
             "Require Import StageGappa ErfcxReciprocal ErfcxTableEntry ErfcxTableCertificateModel ErfcxTableCertificates FastErfcxEvaluation.",
             "Open Scope R_scope."]
    for table, i in rows:
        lines += [f"Require erfcx_fast_{table}_{i:03d}."]
    for j, (table, i) in enumerate(rows):
        e = 0 if j < 49 else (j-49)//32
        value = f"fast_table_value {j} (rn hx)"
        exact = f"table_polynomial_exact {j} (rn hx)"
        lines += [f"Lemma fast_row_{j:03d} hx : -/{2**(6-e)}<=hx<=/{2**(6-e)} ->",
                  f" -7/2^54<=({value}-{exact})/{exact}<=7/2^54 /\\ /64<={value}<=4.",
                  "Proof.", " intros H.",
                  f" destruct row_{j:03d}_words as [C0 [C1 [C2 [C3 [C4 [C5 [C6 [C7 [C8 [C9 [C10 [C11 [C12 [C13 C14]]]]]]]]]]]]]].",
                  " unfold fast_table_value,table_polynomial_exact,tail_coefs.",
                  " cbn [List.seq List.map polynomial_tail].",
                  " rewrite C0,C1,C2,C3,C4,C5,C6,C7,C8,C9,C10,C11,C12.",
                  f" repeat split; erfcx_goal (erfcx_fast_{table}_{i:03d}.l1 hx).", "Qed."]
    lines += ["Theorem fast_table_certificate_rn i hx : (i<177)%nat ->",
              " Rabs hx<=bpow radix2 (table_exponent i-6) ->",
              " -7/2^54<=(fast_table_value i (rn hx)-table_polynomial_exact i (rn hx))/table_polynomial_exact i (rn hx)<=7/2^54 /\\ /64<=fast_table_value i (rn hx)<=4.",
              "Proof.", " intros I H. apply Rabs_le_inv in H."]
    for j in range(177):
        lines += [f" destruct i as [|i];[exact (fast_row_{j:03d} hx H)|]."]
    lines += [" lia.", "Qed.",
              "Theorem fast_table_certificate i h : (i<177)%nat -> F64 h ->",
              " Rabs h<=bpow radix2 (table_exponent i-6) ->",
              " -7/2^54<=(fast_table_value i h-table_polynomial_exact i h)/table_polynomial_exact i h<=7/2^54 /\\ /64<=fast_table_value i h<=4.",
              "Proof.", " intros I F H. pose proof (fast_table_certificate_rn i h I H) as C.",
              " assert (E : rn h=h) by (apply round_generic;[exact _|exact F]).",
              " rewrite E in C;exact C.", "Qed."]
    return "\n".join(lines)+"\n"


def coq_outputs(rows):
    # Match the existing analytic-table layout: independent chunks avoid a
    # single eight-minute certificate assembly and keep per-process memory low.
    full = coq_certificates(rows)
    header = full[:full.index('Lemma fast_row_')]
    header = '\n'.join(line for line in header.splitlines()
                       if not line.startswith('Require erfcx_fast_')) + '\n'
    bodies = re.findall(r'Lemma fast_row_.*?Qed\.\n', full, flags=re.S)
    assert len(bodies) == 177
    outputs = {}
    modules = []
    keys = list(rows)
    for start in range(0, 177, 16):
        module = f'FastErfcxCertificates{start // 16:02d}'
        modules.append(module)
        imports = ''.join(f'Require erfcx_fast_{table}_{i:03d}.\n'
                          for table, i in keys[start:start+16])
        outputs[ROOT / f'formal/fast/{module}.v'] = header + imports + ''.join(bodies[start:start+16])
    aggregate = header.replace(' ErfcxTableCertificates ', ' ')
    aggregate += 'Require Import ' + ' '.join(modules) + '.\n'
    aggregate += full[full.index('Theorem fast_table_certificate_rn'):]
    outputs[ROOT / 'formal/fast/FastErfcxCertificates.v'] = aggregate
    return outputs


def normal_certificate():
    # Existing generated Coq constants bind the same CENTER words as Rust.
    source = (ROOT / 'formal/normal/NormalCenterFastConstants.v').read_text()
    words = re.findall(r'Definition normal_center_(\d+)_hi := b64_of_bits (\d+)\.', source)
    assert len(words) == 13
    lines = ['# Generated by generators/fast_certificates.py; bounded central CDF.',
             '@rnd = float<ieee_64, ne>;']
    for index, word in words:
        lines += [f'a{index} = {hexfloat(hex(int(word)))};']
    for i in range(13):
        lines += [f'c{i} = {(-1)**i}/{2**i*math.factorial(i)*(2*i+1)};']
    lines += ['d = 0x1.9884533d43651p-2;', 'x = rnd(xx);', 'z = rnd(x*x);',
              'zz = rnd(z*z);', 'Z = x*x;', 'ZZ = Z*Z;']
    for i in range(6):
        lines += [f'p{i} = rnd(a{2*i}+rnd(z*a{2*i+1}));',
                  f'q{i} = c{2*i}+Z*c{2*i+1};']
    lines += ['y6 = a12;', 'e6 = c12;']
    for i in reversed(range(6)):
        lines += [f'y{i} = rnd(p{i}+rnd(zz*y{i+1}));',
                  f'e{i} = q{i}+ZZ*e{i+1};']
    lines += ['dx = rnd(x*d);', 'v = rnd(dx*y0);', 'Y = rnd(0.5+v);',
              'P = 0.5+x*(d+delta)*e0;',
              '{ xx in [-1,1] /\\ delta in [-1b-54,1b-54] ->',
              ' Y-P in [-1b-51,1b-51] /\\ Y in [1b-6,1] }',
              'Y-P -> (Y-(0.5+v))+(v-dx*y0)+(dx-x*d)*y0+x*d*(y0-e0)-x*delta*e0;',
              'zz-ZZ -> (zz-z*z)+(z-Z)*(z+Z);']
    for i in range(6):
        lines += [f'y{i}-e{i} -> (y{i}-(p{i}+rnd(zz*y{i+1})))',
                  f' + (rnd(zz*y{i+1})-zz*y{i+1})+(p{i}-q{i})',
                  f' + zz*(y{i+1}-e{i+1})+(zz-ZZ)*e{i+1};',
                  f'p{i}-q{i} -> (p{i}-(a{2*i}+rnd(z*a{2*i+1})))',
                  f' + (rnd(z*a{2*i+1})-z*a{2*i+1})+(a{2*i}-c{2*i})',
                  f' + z*(a{2*i+1}-c{2*i+1})+(z-Z)*c{2*i+1};']
    return '\n'.join(lines)+'\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    rows = erfcx_rows()
    assert len(rows) == 177
    outputs = coq_outputs(rows)
    outputs[ROOT / "formal/normal/fast_center.g"] = normal_certificate()
    for (table, i), row in rows.items():
        path = ROOT / f'formal/erfcx/fast_{table}_{i:03d}.g'
        outputs[path] = certificate(row)
    for path, content in outputs.items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f'stale generated certificate: {path}')
        else:
            path.write_text(content)


if __name__ == '__main__':
    main()
