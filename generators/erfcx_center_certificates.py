#!/usr/bin/env python3
"""Kernel-checked enclosures for the generated erfcx Q256 center values.

Only integer arithmetic is used here. Coq replays every outward-rounded
Gaussian-series step, proves the integral remainder, and checks the final
transcendental enclosure independently with CoqInterval. The source constants
come from erfcx/accurate_tables.py; this generator does not change them.
"""
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "crates/morphiq-numerics/src/erfcx/accurate_tables.rs"
body = SOURCE.read_text().split("pub const F_AT_C:", 1)[1].split("=", 1)[1].split(";", 1)[0]
rows = re.findall(r"\(\s*\[([^]]+)\],\s*(-?\d+),?\s*\)", body)
assert len(rows) == 177
HEADER = '''(** Generated by generators/erfcx_center_certificates.py. *)
From Coq Require Import Reals ZArith Lia Lra.
From Flocq Require Import Core.
From Interval Require Import Tactic.
From Q Require Import Q256 Q256Real.
Require Import StageGappa ErfcxConstants ErfcxAccurateData ErfcxAccurateConstants
  ErfcxAccurateCenterModel ErfcxGaussianSeries ErfcxGaussianBox
  ErfcxGaussianTarget ErfcxGaussianRemainder.
Open Scope R_scope.
'''
outputs = {}
for group in range(12):
    out = HEADER
    for i in range(group * 16, min((group + 1) * 16, len(rows))):
        cn, cd = (i - 16, 32) if i < 49 else (2 ** ((i - 49) // 32) * (65 + 2 * ((i - 49) % 32)), 64)
        bound, degree, precision = next((b, n, p) for b, n, p in
            [(1, 100, 400), (2, 140, 416), (4, 230, 448), (8, 440, 640), (16, 1100, 1200)]
            if abs(cn) <= b * cd)
        scale = 2 ** precision
        lo = hi = sl = sh = scale
        for k in range(degree):
            a, d = cn * cn * (2 * k + 1), cd * cd * (k + 1) * (2 * k + 3)
            lo, hi = -(hi * a // d) - 1, -(lo * a // d)
            sl, sh = sl + lo, sh + hi
        words, exponent = rows[i]
        limbs = [int(x, 16) for x in re.findall(r"0x[0-9a-f]+", words)]
        assert len(limbs) == 4
        mantissa = sum(x << (64 * k) for k, x in enumerate(limbs))
        out += f'''
Definition center_box_{i:03} := box ({lo}) ({hi}) ({sl}) ({sh}).
Lemma center_box_checked_{i:03} :
  gaussian_boxes ({cn}) {cd} (2^{precision}) {degree}=center_box_{i:03}.
Proof. vm_compute; reflexivity. Qed.
Lemma center_error_{i:03} :
  Rabs(qval(q_center {i})-gaussian_erfcx(accurate_center {i}))<=bpow radix2 (-251).
Proof.
  destruct (constant_q_ok _ (f_at_c_data_checked {i} ltac:(lia))) as [Q Value].
  assert (Approx : Rabs(qval(q_center {i})-gaussian_approx {degree} (accurate_center {i}))<=bpow radix2 (-252)).
  {{
    pose proof (proj2(gaussian_boxes_correct ({cn}) {cd} (2^{precision}) {degree} ltac:(lia))) as Bound.
    rewrite center_box_checked_{i:03} in Bound.
    apply contains_divide in Bound; [|apply Z.pow_pos_nonneg; lia].
    unfold center_box_{i:03} in Bound; cbn [sum_lo sum_hi] in Bound.
    change (({sl})/{scale}<=gaussian_sum {degree} (({cn})/{cd})<=({sh})/{scale}) in Bound.
    unfold q_center; rewrite Value.
    change (Rabs(({mantissa}*bpow radix2 ({exponent}))-gaussian_approx {degree} (({cn})/{cd}))<=bpow radix2 (-252)).
    unfold gaussian_approx,inv_sqrt_pi. bpow_num. interval with (i_prec {precision}).
  }}
  assert (Truncation : Rabs(gaussian_erfcx(accurate_center {i})-gaussian_approx {degree} (accurate_center {i}))<=bpow radix2 (-350)).
  {{ apply gaussian_remainder_{bound}. change (Rabs(({cn})/{cd})<={bound}). apply Rabs_le; split; lra. }}
  replace (qval(q_center {i})-gaussian_erfcx(accurate_center {i})) with
    ((qval(q_center {i})-gaussian_approx {degree} (accurate_center {i}))+
     (gaussian_approx {degree} (accurate_center {i})-gaussian_erfcx(accurate_center {i}))) by ring.
  eapply Rle_trans; [apply Rabs_triang|]. rewrite (Rabs_minus_sym (gaussian_approx _ _) _).
  assert (Budget : bpow radix2 (-252)+bpow radix2 (-350)<=bpow radix2 (-251)) by (bpow_num; lra).
  lra.
Qed.
'''
    outputs[f"ErfcxAccurateCenters{group:02}.v"] = out
out = HEADER + "Require Import " + " ".join(f"ErfcxAccurateCenters{g:02}" for g in range(12)) + ".\n"
out += '''Theorem q_center_ok i : (i<177)%nat -> valid(q_center i) /\\
  Rabs(qval(q_center i)-gaussian_erfcx(accurate_center i))<=bpow radix2 (-251).
Proof.
  intros I. split.
  - exact (proj1(constant_q_ok _ (f_at_c_data_checked i I))).
  -
'''
for i in range(177):
    out += f"    destruct i as [|i]; [exact center_error_{i:03}|].\n"
out += "    lia.\nQed.\n"
outputs["ErfcxAccurateCenters.v"] = out
for name, text in outputs.items():
    path = ROOT / "formal/erfcx" / name
    if "--check" in sys.argv:
        assert path.read_text() == text, f"{path} differs"
    else:
        path.write_text(text)
