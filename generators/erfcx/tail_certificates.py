"""Generate erfcx certificates that depend on generated polynomial constants.

The remaining component certificates contain only exact mathematical constants
and error budgets. All certificates are conditional arithmetic statements;
docs/erfcx.md records the binary64 entry obligations that remain.
"""
import pathlib
import struct
import sys

root = pathlib.Path(__file__).resolve().parents[2]
out = pathlib.Path(sys.argv[1])
out.mkdir(parents=True, exist_ok=True)
pa = []
constants = {}
for line in (root / "generators/erfcx/tables.out").read_text().splitlines():
    fields = line.split()
    if fields[0] == "PA":
        pa.append(struct.unpack(">d", int(fields[2], 16).to_bytes(8, "big"))[0])
    elif fields[0] in ("CS", "CSL"):
        constants[fields[0]] = struct.unpack(">d", int(fields[1], 16).to_bytes(8, "big"))[0].hex()

assert len(pa) == 8
coefficients = "\n".join(f"a{i} = {a.hex()};" for i, a in enumerate(pa)) + "\n"


def horner(x):
    value = "a7"
    for i in range(6, -1, -1):
        value = f"a{i} + {x} * ({value})"
    return value


def difference(x, y, first, last, offset):
    """The divided difference of sum a[i-offset] * x^i, by factorization."""
    return " + ".join(
        f"a{i-offset} * (" + " + ".join(
            "*".join([x] * (i - 1 - j) + [y] * j) or "1"
            for j in range(i)
        ) + ")" for i in range(first, last + 1)
    )


header = "# Generated by generators/erfcx/tail_certificates.py; do not edit.\n"
s = header + "# Middle-tail polynomial; exact EFTs/high-word half, rounded low-word half.\n"
s += "@rnd = float<ieee_64, ne>;\n" + coefficients
s += "th = rnd(th_);\ntl = rnd(tl_);\nt = th + tl;\n"
for i in range(6, -1, -1):
    previous = "a7" if i == 6 else f"p{i+1}"
    s += f"p{i} = rnd(a{i} + rnd(th * {previous}));\n"
s += f"PH = {horner('th')};\nPT = {horner('t')};\n"
s += r"""w = rnd(1 - (1 / 2) * th);
ew = 1 - (1 / 2) * th - w;
v0 = rnd(th + 2 * tl);
v1 = rnd(th * v0);
v = rnd(v1 * p0);
w2 = rnd(w + v);
e3 = w + v - w2;
half_tl = rnd((1 / 2) * tl);
wl0 = rnd(ew - half_tl);
wl = rnd(e3 + wl0);
W = w2 + wl;
S = 1 - t / 2 + t * t * PT;
{ th in [1b-18, 1b-8] /\ tl / th in [-1b-51, 1b-51]
  -> W - S in [-0x1.5p-68, 0x1.5p-68] /\ W in [0.998, 1.001]
     /\ w2 in [0.998, 1.001] /\ wl / w2 in [-1b-51, 1b-51]
     /\ p0 in [0, 1] /\ w in [0.99, 1] /\ v in [0, 1b-15] }
W - S -> (wl - (e3 + wl0)) + (wl0 - (ew - half_tl)) - (half_tl - (1 / 2) * tl) + (v - t * t * PT);
v - t * t * PT -> (v - v1 * p0) + (v1 - th * v0) * p0 + th * (v0 - (th + 2 * tl)) * p0 - tl * tl * p0 + t * t * ((p0 - PH) + (PH - PT));
tl -> th * (tl / th) { th <> 0 };
"""
s += f"PH - PT -> -tl * ({difference('th', 't', 1, 7, 0)});\n"
(out / "middle_polynomial.g").write_text(s)

s = header + "# Sensitivity to the reciprocal/square error, by exact factorization.\n"
s += coefficients + "t = T + dt;\n"
s += f"St = 1 - t / 2 + t * t * ({horner('t')});\n"
s += f"ST = 1 - T / 2 + T * T * ({horner('T')});\n"
s += r"""{ T in [1b-18, 1b-8] /\ dt in [-1b-102, 1b-102]
  -> St - ST in [-1b-101, 1b-101] }
"""
s += f"St - ST -> dt * (-(1 / 2) + {difference('t', 'T', 2, 9, 2)});\n"
(out / "middle_mvt.g").write_text(s)

# Bounded exponent windows retain a useful absolute-to-relative conversion
# for the final division's error, while modeling gradual underflow directly.
# The union is [2^9, 2^897], covering both unscaled and scaled tail inputs.
s = header + "# Direct IEEE quotient correction; exact TwoProd/Sterbenz are entry obligations.\n"
s += "@rnd = float<ieee_64, ne>;\n"
s += f"ch = {constants['CS']};\ncl = {constants['CSL']};\n"
s += r"""x = rnd(x_);
q = rnd(ch / x);
p = rnd(q * x);
pe = q * x - p;
r1 = rnd((ch - p) - pe);
r = rnd(r1 + cl);
ql = rnd(r / x);
Q = q + ql;
C = (ch + cl) / x;
{ x in [LOWER, UPPER] -> (Q - C) / C in [-1b-70, 1b-70] /\ ql / q in [-1b-51, 1b-51]
 /\ q in [1b-899,1b-9] /\ p in [0.5,0.625] /\ pe in [-1b-52,1b-52]
 /\ r1 in [-1b-50,1b-50] /\ r in [-1b-50,1b-50] /\ ql in [-1b-59,1b-59] }
Q - C -> (ql - r / x) + ((r - (r1 + cl)) + (r1 - ((ch - p) - pe))) / x { x <> 0 };
ch - p - pe -> -(q - ch / x) * x { x <> 0 };
q*x -> ch*(1+(q-ch/x)/(ch/x)) { x <> 0, ch <> 0 };
ch-p-pe -> -((q-ch/x)/(ch/x))*ch { x <> 0, ch <> 0 };
(Q-C)/C -> ((ql-r/x)*x + (r-(r1+cl)) + (r1-((ch-p)-pe)))/(ch+cl) { x <> 0, ch+cl <> 0 };
ql/q -> ((ql-r/x)*x+r)/(q*x) { q <> 0, x <> 0 };
"""
for index, lower in enumerate(range(9, 897, 32)):
    upper = min(lower + 32, 897)
    certificate = s.replace("LOWER", f"1b{lower}").replace("UPPER", f"1b{upper}")
    (out / f"tail_quotient_{index:02}.g").write_text(certificate)

