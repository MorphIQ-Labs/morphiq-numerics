#!/usr/bin/env python3
"""Generate the normal-family constants at 600 and 1000 bits.

The centered-CDF coefficients are the exact integrated Gaussian series,
(-1)^n / (2^n n! (2n+1)); no external approximation coefficients are used.
"""
import pathlib
import math
import struct
import subprocess
import sys
import mpmath as mp

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT = ROOT / 'crates/morphiq-numerics/src/normal_distribution/tables.rs'
COQ_OUT = ROOT / 'formal/normal/NormalConstants.v'
OVERFLOW_OUT = ROOT / 'formal/normal/NormalLogOverflowConstants.v'
TAIL_OUT = ROOT / 'formal/normal/NormalTailThresholdConstants.v'
FAST_CENTER_OUT = ROOT / 'formal/normal/NormalCenterFastConstants.v'

def bits(x):
    return struct.unpack('>Q', struct.pack('>d', float(x)))[0]

def word(x):
    return f'f64::from_bits(0x{bits(x):016x})'

def dw(x):
    h = float(x)
    return f'({word(h)}, {word(x-mp.mpf(h))})'

def q_parts(x):
    negative = x < 0
    x = abs(x)
    e = int(mp.floor(mp.log(x, 2))) - 255
    m = int(mp.nint(mp.ldexp(x, -e)))
    if m == 1 << 256:
        m >>= 1
        e += 1
    return negative, m, e

def q(x):
    negative, m, e = q_parts(x)
    limbs = ', '.join(f'0x{(m >> (64*i)) & ((1<<64)-1):016x}' for i in range(4))
    return f'Q256::new({str(negative).lower()}, [{limbs}], {e})'

def saturation_boundaries():
    def tail_boundary(bits_):
        return mp.findroot(lambda x: mp.log(mp.erfc(x/mp.sqrt(2))/2)+bits_*mp.log(2),
                           (38,39) if bits_==1075 else (8,9))
    return {
        'PDF_ZERO': mp.sqrt(2*(1075*mp.log(2)-mp.log(2*mp.pi)/2)),
        'TAIL_ZERO': tail_boundary(1075),
        'CDF_ONE': tail_boundary(54),
        'CENTERED_HALF': tail_boundary(55),
        # The log-tail correction is less than 1028 in magnitude for every
        # finite binary64 input. Coq proves that this cannot move the cutoff
        # across either adjacent input around this half-square estimate.
        'LOG_OVERFLOW': mp.sqrt(2*(mp.ldexp(1,1024)-mp.ldexp(1,970))),
    }

def first_above(boundary):
    first = float(boundary)
    return math.nextafter(first, math.inf) if mp.mpf(first) < boundary else first

def coq_overflow(precision):
    with mp.workprec(precision):
        n = bits(first_above(saturation_boundaries()['LOG_OVERFLOW']))
        fraction = n & ((1 << 52)-1)
        exponent = (n >> 52) & 2047
        m = fraction + (1 << 52)
        e = exponent-1075
        return f'''(** Generated by generators/normal_constants.py. The square brackets
    include the full log-tail correction and the Q256 composition error. *)
From Coq Require Import Reals ZArith Lia Lra.
From Flocq Require Import Core IEEE754.Bits.
From Interval Require Import Tactic.
From Binary64 Require Import IEEE64 Encodings.
Require Import StageGappa.
Open Scope R_scope.
Definition normal_log_overflow := b64_of_bits {n}.
Lemma normal_log_overflow_ok : finite normal_log_overflow /\\
  B normal_log_overflow={m}*bpow radix2 {e}.
Proof.
  exact(join_val {fraction} {exponent} ltac:(lia) ltac:(lia)).
Qed.
Theorem normal_log_overflow_bracket :
  bpow radix2 1024-bpow radix2 970 <
    B normal_log_overflow*B normal_log_overflow/2-1028 /\\
  (((B normal_log_overflow-bpow radix2 {e})*
    (B normal_log_overflow-bpow radix2 {e})/2)+1028)*(1+bpow radix2 (-112)) <
    9007199254740991*bpow radix2 971.
Proof.
  destruct normal_log_overflow_ok as [_ Value];rewrite Value.
  bpow_num;split;interval with(i_prec 200).
Qed.
'''

def coq_tail_thresholds(precision):
    with mp.workprec(precision):
        text = '''(** Generated by generators/normal_constants.py. Each endpoint is
    checked by integer evaluation of the proved Q256 tail, with an explicit
    margin exceeding its evaluation error. *)
From Coq Require Import Reals ZArith Lia Lra.
From Flocq Require Import Core IEEE754.Bits.
From Interval Require Import Tactic.
From Binary64 Require Import IEEE64 Encodings.
Require Import StageGappa NormalAccurateTailFull NormalTailThresholdCheck NormalTailAnalytic.
Open Scope R_scope.
'''
        for name, power in [('TAIL_ZERO',1075), ('CDF_ONE',54), ('CENTERED_HALF',55)]:
            n = bits(first_above(saturation_boundaries()[name]))
            symbol = 'normal_'+name.lower()
            for suffix, encoded in [('',n), ('_previous',n-1)]:
                m = (encoded & ((1 << 52)-1)) | (1 << 52)
                k = 1075-((encoded >> 52) & 2047)
                text += f'''Definition {symbol}{suffix} := b64_of_bits {encoded}.
Lemma {symbol}{suffix}_ok : finite {symbol}{suffix} /\\ B {symbol}{suffix}={m}/2^{k}.
Proof.
  split.
  - exact(bits_finite {encoded} false {m} (-{k}) eq_refl).
  - exact(bits_val {encoded} false {m} {k} eq_refl).
Qed.
Lemma {symbol}{suffix}_checked :
  normal_tail_threshold_check {power} {str(not suffix).lower()} (normal_q_tail {symbol}{suffix})=true.
Proof. vm_compute;reflexivity. Qed.
'''
            text += f'''Theorem {symbol}_tail_bracket :
  normal_tail (B {symbol}) < bpow radix2 (-{power}) /\\
  bpow radix2 (-{power}) < normal_tail(B {symbol}_previous).
Proof.
  destruct {symbol}_ok as[F Value];destruct {symbol}_previous_ok as[FP Previous].
  split.
  - exact(normal_tail_threshold_certified {symbol} {power} true F
      ltac:(rewrite Value;split;interval with(i_prec 80)) {symbol}_checked).
  - exact(normal_tail_threshold_certified {symbol}_previous {power} false FP
      ltac:(rewrite Previous;split;interval with(i_prec 80)) {symbol}_previous_checked).
Qed.
'''
        return text

def coq_constants(precision):
    with mp.workprec(precision):
        constants = {
            'density': (1/mp.sqrt(2*mp.pi), '/sqrt(2*PI)'),
            'inv_sqrt2': (1/mp.sqrt(2), '/sqrt 2'),
            'two_inv_sqrt_pi': (2/mp.sqrt(mp.pi), '2/sqrt PI'),
            'ln2': (mp.log(2), 'ln 2'),
            'ln_sqrt_2pi': (mp.log(2*mp.pi)/2, 'ln(2*PI)/2'),
        }
        text = '''(** Generated by generators/normal_constants.py. The kernel checks
    the encoded words and CoqInterval certifies their mathematical errors. *)
From Coq Require Import Reals ZArith Lia Lra List.
From Flocq Require Import Core IEEE754.Binary IEEE754.Bits.
From Interval Require Import Tactic.
From Binary64 Require Import IEEE64 Encodings.
From Q Require Import Q256 Q256Real.
Require Import StageGappa ErfcxAccurateData ErfcxAccurateConstants.
Import ListNotations.
Open Scope R_scope.
'''
        for name, (value, target) in constants.items():
            hi = float(value)
            lo = float(value-mp.mpf(hi))
            for suffix, v in [('hi', hi), ('lo', lo)]:
                n = bits(v)
                sign = str(v < 0).lower()
                m = (n & ((1 << 52)-1)) | (1 << 52)
                e = ((n >> 52) & 2047)-1023-52
                signed = -m if v < 0 else m
                symbol = f'normal_{name}_{suffix}'
                text += f'''Definition {symbol} := b64_of_bits {n}.
Lemma {symbol}_ok : finite {symbol} /\\ B {symbol}={signed}/2^{-e}.
Proof.
  split.
  - exact(bits_finite {n} {sign} {m} ({e}) eq_refl).
  - exact(bits_val {n} {sign} {m} {-e} eq_refl).
Qed.
'''
            text += f'''Theorem normal_{name}_dw_error :
  Rabs((B normal_{name}_hi+B normal_{name}_lo)/({target})-1)<=bpow radix2 (-105).
Proof.
  destruct normal_{name}_hi_ok as [_ H],normal_{name}_lo_ok as [_ L].
  rewrite H,L. bpow_num. apply Rabs_le;split;interval with(i_prec 200).
Qed.
'''
            if name in ('two_inv_sqrt_pi', 'ln_sqrt_2pi'):
                continue
            negative, m, e = q_parts(value)
            assert not negative
            limbs = '; '.join(f'{(m >> (64*i)) & ((1<<64)-1)}%Z' for i in range(4))
            text += f'''Definition normal_{name}_data : constant := ([{limbs}],({e})%Z).
Definition normal_q_{name} := constant_q normal_{name}_data.
Lemma normal_{name}_data_checked : constant_check normal_{name}_data=true.
Proof. vm_compute;reflexivity. Qed.
Theorem normal_q_{name}_error : valid normal_q_{name} /\\
  Rabs(qval normal_q_{name}/({target})-1)<=bpow radix2 (-255).
Proof.
  destruct(constant_q_ok _ normal_{name}_data_checked) as [Q Value].
  split;[exact Q|]. unfold normal_q_{name}. rewrite Value.
  change(Rabs(({m}*bpow radix2 ({e}))/({target})-1)<=bpow radix2 (-255)).
  bpow_num. apply Rabs_le;split;interval with(i_prec 400).
Qed.
'''
        text += 'Definition normal_center_data : list constant := [\n'
        rows = []
        for n in range(41):
            _, m, e = q_parts(1/(mp.factorial(n)*(2*n+1)))
            limbs = '; '.join(f'{(m >> (64*i)) & ((1<<64)-1)}%Z' for i in range(4))
            rows.append(f'([{limbs}],({e})%Z)')
        text += ';\n'.join(rows)+'].\n'
        text += '''Lemma normal_center_data_checked : forallb constant_check normal_center_data=true.
Proof. vm_compute;reflexivity. Qed.
'''
        cutoff = first_above(saturation_boundaries()['PDF_ZERO'])
        n = bits(cutoff)
        m = (n & ((1 << 52)-1)) | (1 << 52)
        k = 1075-((n >> 52) & 2047)
        text += f'''Definition normal_pdf_zero := b64_of_bits {n}.
Lemma normal_pdf_zero_ok : finite normal_pdf_zero /\\ B normal_pdf_zero={m}/2^{k}.
Proof.
  split.
  - exact(bits_finite {n} false {m} (-{k}) eq_refl).
  - exact(bits_val {n} false {m} {k} eq_refl).
Qed.
Theorem normal_pdf_zero_bracket :
  exp(-B normal_pdf_zero*B normal_pdf_zero/2)/sqrt(2*PI)<bpow radix2 (-1075) /\\
  bpow radix2 (-1075)<exp(-(B normal_pdf_zero-bpow radix2 (-{k})) *
    (B normal_pdf_zero-bpow radix2 (-{k}))/2)/sqrt(2*PI).
Proof.
  destruct normal_pdf_zero_ok as [_ Value]. rewrite Value.
  bpow_num. split;interval with(i_prec 200).
Qed.
'''
        return text

def coq_fast_center(precision):
    with mp.workprec(precision):
        text = '''(** Generated by generators/normal_constants.py. These are the exact
    binary64 words used by the mixed-precision centered-CDF polynomial. *)
From Coq Require Import Reals ZArith Lia Lra List.
From Flocq Require Import Core IEEE754.Binary IEEE754.Bits.
From Interval Require Import Tactic.
From Binary64 Require Import IEEE64 Encodings.
Require Import StageGappa ErfcxFactorial.
Import ListNotations.
Open Scope R_scope.
Definition normal_fast_center_coefficient n : R :=
  (-1)^n/(2^n*INR(fact n)*INR(S(2*n))).
'''
        for n in range(13):
            c = (-mp.mpf(1))**n/(2**n*mp.factorial(n)*(2*n+1))
            hi = float(c)
            lo = float(c-mp.mpf(hi))
            for suffix, v in [('hi', hi), ('lo', lo)]:
                symbol = f'normal_center_{n}_{suffix}'
                code = bits(v)
                numerator, denominator = v.as_integer_ratio()
                text += f'Definition {symbol} := b64_of_bits {code}.\n'
                text += f'Lemma {symbol}_ok : finite {symbol} /\\ B {symbol}={numerator}/{denominator}.\nProof.\n'
                if v == 0:
                    text += '  split;[reflexivity|change(0=0/1);field].\n'
                else:
                    mantissa = (code & ((1 << 52)-1)) | (1 << 52)
                    exponent = ((code >> 52) & 2047)-1075
                    sign = str(v < 0).lower()
                    text += f'''  split.
  - exact(bits_finite {code} {sign} {mantissa} ({exponent}) eq_refl).
  - pose proof(bits_val {code} {sign} {mantissa} {-exponent} eq_refl)as V.
    unfold {symbol};rewrite V;change({-mantissa if v < 0 else mantissa}/2^{-exponent}={numerator}/{denominator});field.
'''
                text += 'Qed.\n'
        text += 'Definition normal_center_fast_words := [\n'
        text += ';\n'.join(f'(normal_center_{n}_hi,normal_center_{n}_lo)' for n in range(13))+'].\n'
        text += '''Definition normal_center_fast_word n := nth n normal_center_fast_words (b64_of_bits 0,b64_of_bits 0).
Theorem normal_center_fast_words_ok n : (n<13)%nat ->
  let '(h,l):=normal_center_fast_word n in finite h /\\ finite l /\\
    Rabs((B h+B l)-normal_fast_center_coefficient n)<=bpow radix2 (-105).
Proof.
  intros N. unfold normal_center_fast_word,normal_center_fast_words.
'''
        for n in range(13):
            text += f'''  destruct n as[|n].
  - cbn [nth];destruct normal_center_{n}_hi_ok as[Fh H],normal_center_{n}_lo_ok as[Fl L].
    split;[exact Fh|];split;[exact Fl|];rewrite H,L.
    unfold normal_fast_center_coefficient;binary_factorials;repeat rewrite INR_IZR_INZ;cbn [Nat.mul Nat.add Z.of_nat];bpow_num;interval with(i_prec 180).
'''
        text += '  lia.\nQed.\n'
        text += '''Theorem normal_center_fast_tail_word n : (4<=n<13)%nat ->
  finite(fst(normal_center_fast_word n)) /\\
  Rabs(B(fst(normal_center_fast_word n)))<=bpow radix2 (-11) /\\
  Rabs(B(fst(normal_center_fast_word n))-normal_fast_center_coefficient n)<=bpow radix2 (-65).
Proof.
  intros N. unfold normal_center_fast_word,normal_center_fast_words.
'''
        for n in range(13):
            text += '  destruct n as[|n].\n'
            if n < 4:
                text += '  - lia.\n'
            else:
                text += f'''  - cbn [nth fst];destruct normal_center_{n}_hi_ok as[F H].
    split;[exact F|];rewrite H;unfold normal_fast_center_coefficient;binary_factorials;repeat rewrite INR_IZR_INZ;cbn [Nat.mul Nat.add Z.of_nat];bpow_num;
      split;interval with(i_prec 180).
'''
        text += '  lia.\nQed.\n'
        return text

def generate(precision):
    with mp.workprec(precision):
        constants = {'DENSITY': 1/mp.sqrt(2*mp.pi), 'INV_SQRT2': 1/mp.sqrt(2),
                     'TWO_INV_SQRT_PI': 2/mp.sqrt(mp.pi), 'LN2': mp.log(2),
                     'LN_SQRT_2PI': mp.log(2*mp.pi)/2}
        text = '//! Generated by generators/normal_constants.py; do not edit.\n'
        text += 'use crate::q256::Q256;\n'
        for name, x in constants.items():
            text += f'pub(super) const {name}: (f64, f64) = {dw(x)};\n'
            if name not in ('TWO_INV_SQRT_PI', 'LN_SQRT_2PI'):
                text += f'pub(super) fn q_{name.lower()}() -> Q256 {{ {q(x)} }}\n'
        coeffs = [(-mp.mpf(1))**n/(2**n*mp.factorial(n)*(2*n+1)) for n in range(13)]
        text += 'pub(super) const CENTER: [(f64, f64); 13] = [\n'
        text += ''.join(dw(c)+',\n' for c in coeffs)+'];\n'
        # The accurate Horner path uses z=-x*x/2 and positive coefficients.
        # Precomputing these avoids repeated Newton reciprocals at runtime.
        text += 'pub(super) const Q_CENTER: [([u64; 4], i32); 41] = [\n'
        for n in range(41):
            _, m, e = q_parts(1/(mp.factorial(n)*(2*n+1)))
            limbs = ', '.join(f'0x{(m >> (64*i)) & ((1<<64)-1):016x}' for i in range(4))
            text += f'([{limbs}], {e}),\n'
        text += '];\n'
        for name, boundary in saturation_boundaries().items():
            text += f'pub(super) const {name}: f64 = {word(first_above(boundary))};\n'
        return subprocess.run(['rustfmt','--edition','2024'],input=text,text=True,
                              check=True,capture_output=True).stdout

def main():
    text = generate(600)
    assert text == generate(1000), 'normal constants are not precision-stable'
    coq = coq_constants(600)
    assert coq == coq_constants(1000), 'normal proof constants are not precision-stable'
    overflow = coq_overflow(600)
    assert overflow == coq_overflow(1000), 'normal overflow bracket is not precision-stable'
    tail = coq_tail_thresholds(600)
    assert tail == coq_tail_thresholds(1000), 'normal tail brackets are not precision-stable'
    fast_center = coq_fast_center(600)
    assert fast_center == coq_fast_center(1000), 'normal fast center words are not precision-stable'
    if '--check' in sys.argv:
        assert OUT.read_text() == text, 'normal constants differ'
        assert COQ_OUT.read_text() == coq, 'normal proof constants differ'
        assert OVERFLOW_OUT.read_text() == overflow, 'normal overflow proof constants differ'
        assert TAIL_OUT.read_text() == tail, 'normal tail proof constants differ'
        assert FAST_CENTER_OUT.read_text() == fast_center, 'normal fast center proof words differ'
    else:
        OUT.write_text(text)
        COQ_OUT.write_text(coq)
        OVERFLOW_OUT.write_text(overflow)
        TAIL_OUT.write_text(tail)
        FAST_CENTER_OUT.write_text(fast_center)
    print('normal constants: 600/1000-bit agreement')

if __name__ == '__main__': main()
