#!/usr/bin/env python3
"""Certify the stored table against a 48th-degree rational ODE polynomial.

All arithmetic here is exact Fraction arithmetic. Coq independently checks
its recurrence, input constants, differences, analytic Taylor remainder and
interval enclosures. No implementation or approximation is generated.
"""
from pathlib import Path
from fractions import Fraction
import re
import struct
import sys

ROOT = Path(__file__).resolve().parents[1]
source = (ROOT / 'crates/morphiq-numerics/src/erfcx/accurate_tables.rs').read_text()
rows = re.findall(r'\(\s*\[([^]]+)\],\s*(-?\d+),?\s*\)', source.split('pub const F_AT_C:', 1)[1].split('=', 1)[1].split(';', 1)[0])
assert len(rows) == 177

def constant(words, exponent):
    limbs = [int(x, 16) for x in re.findall(r'0x[0-9a-f]+', words)]
    assert len(limbs) == 4
    mantissa = sum(x << (64*k) for k, x in enumerate(limbs))
    return Fraction(mantissa) * Fraction(2) ** int(exponent), mantissa, int(exponent)

c2, c2m, c2e = constant(*re.search(r'pub const C2: C =\s*\(\s*\[([^]]+)\],\s*(-?\d+),?\s*\)', source).groups())
fast = {}
for line in (ROOT / 'generators/erfcx/tables.out').read_text().splitlines():
    fields = line.split()
    if fields and fields[0] in ('T0', 'T1') and fields[2] in ('A', 'L'):
        value = float.fromhex(fields[4]) if 'p' in fields[4] else struct.unpack('>d', struct.pack('>Q', int(fields[4], 16)))[0]
        fast.setdefault((fields[0], int(fields[1])), {})[fields[2], int(fields[3])] = Fraction(value)
assert len(fast) == 177

def rat(q):
    return f'({q.numerator}#{q.denominator})%Q'

def real(q):
    return f'({q.numerator}/{q.denominator})'

def qlist(qs):
    return '['+';'.join(rat(q) for q in qs)+']'

header = '''(** Generated by generators/erfcx_table_analytic.py; exact rational certificates. *)
From Coq Require Import Reals ZArith Lia Lra List QArith Qreals.
From Flocq Require Import Core.
From Interval Require Import Tactic.
From Gappa Require Import Gappa_library.
From Binary64 Require Import IEEE64.
From Q Require Import Q256 Q256Real.
Require Import StageGappa ErfcxGaussianTarget ErfcxAccurateCenterModel
  ErfcxAccurateData ErfcxAccurateConstants ErfcxAccurateTaylorInitial
  ErfcxTableEntry ErfcxTableEvaluation ErfcxTableCertificateModel ErfcxTableCertificates
  ErfcxRationalPolynomial ErfcxRationalTableModel.
Import ListNotations.
Open Scope R_scope.
'''
outputs = {}
for group in range(12):
    out = header
    for i in range(group*16, min((group+1)*16, 177)):
        label = f'{i:03}'
        c = Fraction(i-16, 32) if i < 49 else Fraction(2**((i-49)//32)*(65+2*((i-49)%32)),64)
        radius = Fraction(1,64) if i < 49 else Fraction(2**((i-49)//32),64)
        a0, mantissa, exponent = constant(*rows[i])
        a1 = 2*c*a0-c2
        coefficients = [a0,a1]
        for k in range(2,49):
            coefficients.append((2*c*coefficients[-1]+2*coefficients[-2])/k)
        row = fast[sorted(fast)[i]]
        stored = [row['A', k]+row.get(('L',k),0) for k in range(10)]+[Fraction(0)]*39
        difference = [p-t for p,t in zip(stored,coefficients)]
        out += f'''
Definition analytic_series_{label} : list QArith_base.Q := {qlist(coefficients)}.
Definition analytic_stored_{label} : list QArith_base.Q := {qlist(stored)}.
Definition analytic_difference_{label} : list QArith_base.Q := {qlist(difference)}.
Lemma analytic_recurrence_{label} : rat_recurrence_check {rat(c)} {rat(a0)} {rat(a1)} analytic_series_{label}=true.
Proof. vm_compute;reflexivity. Qed.
Lemma analytic_difference_checked_{label} :
  rat_difference analytic_stored_{label} analytic_series_{label}=analytic_difference_{label}.
Proof. vm_compute;reflexivity. Qed.
Lemma analytic_seeds_{label} :
  Q2R {rat(c)}=accurate_center {i} /\\
  Q2R {rat(a0)}=qval(q_center {i}) /\\
  Q2R {rat(a1)}=2*Q2R {rat(c)}*Q2R {rat(a0)}-qval q_c2.
Proof.
  split.
  - change ({real(c)}=accurate_center {i}).
    unfold accurate_center,center_numerator,center_denominator;vm_compute;field.
  - split.
    + symmetry. unfold q_center. rewrite (proj2(constant_q_ok _ (f_at_c_data_checked {i} ltac:(lia)))).
      change ({mantissa}*bpow radix2 ({exponent})={real(a0)}). bpow_num;field.
    + unfold q_c2. rewrite (proj2(constant_q_ok _ c2_data_checked)).
      change ({real(a1)}=2*{real(c)}*{real(a0)}-{c2m}*bpow radix2 ({c2e})). bpow_num;field.
Qed.
Lemma analytic_stored_value_{label} h : table_polynomial_exact {i} h=rat_horner h analytic_stored_{label}.
Proof.
  destruct row_{label}_words as [C0 [C1 [C2 [C3 [C4 [C5 [C6 [C7 [C8 [C9 [C10 [C11 [C12 Rest]]]]]]]]]]]]].
  unfold table_polynomial_exact,tail_coefs,analytic_stored_{label}.
  cbn [seq map polynomial_tail rat_horner].
  rewrite C0,C1,C2,C3,C4,C5,C6,C7,C8,C9,C10,C11,C12.
  unfold Q2R,float2R,F2R{",Float1" if any(v.denominator == 1 for v in row.values()) else ""};cbn. bpow_num;field.
Qed.
Lemma analytic_difference_bound_{label} h : Rabs h<={real(radius)} ->
  Rabs(rat_horner h analytic_difference_{label})<=3*bpow radix2 (-71)*Q2R {rat(a0)}.
Proof.
  intros H;apply Rabs_le_inv in H. unfold analytic_difference_{label}.
  cbn [rat_horner]. unfold Q2R;cbn [Qnum Qden]. bpow_num.
  interval with(i_prec 160,i_bisect h).
Qed.
Lemma analytic_lower_{label} h : Rabs h<={real(radius)} ->
  0.9*Q2R {rat(a0)}<=rat_horner h analytic_series_{label}.
Proof.
  intros H;apply Rabs_le_inv in H. unfold analytic_series_{label}.
  cbn [rat_horner]. unfold Q2R;cbn [Qnum Qden]. interval with(i_prec 160).
Qed.
Lemma analytic_row_{label} h : Rabs h<={real(radius)} ->
  0<gaussian_erfcx(accurate_center {i}+h) /\\
  Rabs((table_polynomial_exact {i} h-gaussian_erfcx(accurate_center {i}+h))/
    gaussian_erfcx(accurate_center {i}+h))<=bpow radix2 (-69).
Proof.
  intros H. destruct analytic_seeds_{label} as [C [A0 A1]].
  pose proof(rational_table_error {i} _ _ _ analytic_series_{label} h ltac:(lia)
    C A0 A1 analytic_recurrence_{label} eq_refl ltac:(lra)) as Error.
  rewrite analytic_stored_value_{label}.
  apply rational_enclosure_relative with(t:=rat_horner h analytic_series_{label})(a0:=Q2R {rat(a0)}).
  - unfold Q2R;cbn [Qnum Qden];interval with(i_prec 80).
  - exact Error.
  - apply analytic_lower_{label};exact H.
  - rewrite <- rat_horner_difference by reflexivity.
    rewrite analytic_difference_checked_{label}. apply analytic_difference_bound_{label};exact H.
Qed.
'''
    outputs[f'ErfcxTableAnalytic{group:02}.v'] = out
out = header + 'Require Import ' + ' '.join(f'ErfcxTableAnalytic{g:02}' for g in range(12)) + '.\n'
out += """Theorem table_analytic_certificate i h : (i<177)%nat ->
  Rabs h<=bpow radix2 (table_exponent i)/64 ->
  0<gaussian_erfcx(accurate_center i+h) /\\
  Rabs((table_polynomial_exact i h-gaussian_erfcx(accurate_center i+h))/
    gaussian_erfcx(accurate_center i+h))<=bpow radix2 (-69).
Proof.
  intros I H.
"""
for i in range(177):
    exponent = 0 if i < 49 else (i-49)//32
    out += f'  destruct i as [|i];[apply analytic_row_{i:03};change (Rabs h<=bpow radix2 {exponent}/64) in H;bpow_num_all;lra|].\n'
out += '  lia.\nQed.\n'
outputs['ErfcxTableAnalytic.v'] = out
out = header + 'Require Import ' + ' '.join(f'ErfcxTableAnalytic{g:02}' for g in range(12)) + '.\n'
for i in range(32,177):
    radius = Fraction(1,64) if i<49 else Fraction(2**((i-49)//32),64)
    condition = f'0<=h<={real(radius)}' if i==32 else f'Rabs h<={real(radius)}'
    prepare = 'intros H.' if i==32 else 'intros H;apply Rabs_le_inv in H.'
    out += f"""Lemma reflection_polynomial_{i:03} h : {condition} ->
  0.034<=table_polynomial_exact {i} h<=0.616.
Proof.
  {prepare} rewrite analytic_stored_value_{i:03}.
  unfold analytic_stored_{i:03};cbn [rat_horner]. unfold Q2R;cbn [Qnum Qden].
  split;interval with(i_prec 100,i_bisect h).
Qed.
"""
out += """Theorem reflection_polynomial_certificate i h : (32<=i<177)%nat ->
  Rabs h<=bpow radix2 (table_exponent i)/64 -> (i=32%nat -> 0<=h) ->
  0.034<=table_polynomial_exact i h<=0.616.
Proof.
  intros I H Positive.
"""
for i in range(177):
    if i<32:
        out += '  destruct i as [|i];[lia|].\n'
    else:
        exponent=0 if i<49 else (i-49)//32
        positive = 'specialize(Positive eq_refl);apply Rabs_le_inv in H;' if i==32 else ''
        out += f'  destruct i as [|i];[apply reflection_polynomial_{i:03};change(Rabs h<=bpow radix2 {exponent}/64) in H;bpow_num_all;{positive}lra|].\n'
out += '  lia.\nQed.\n'
outputs['ErfcxTableReflectionRanges.v'] = out
for name,text in outputs.items():
    path=ROOT/'formal/erfcx'/name
    if '--check' in sys.argv:
        assert path.read_text()==text, f'{path} differs'
    else:
        path.write_text(text)
