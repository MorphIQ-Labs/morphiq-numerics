#!/usr/bin/env python3
"""Generate the bounded Box–Muller angular polynomials at 200 bits.

Six binary64 coefficients for sin(sqrt(z))/sqrt(z) and cos(sqrt(z)),
Chebyshev interpolation on [0, RN(pi/4)^2]. No external coefficients.
Writes Rust constants, Coq constants, Gappa evaluation certificates and
the Sollya script which certifies the rounded polynomials independently.
"""
from pathlib import Path
import struct
import sys

import mpmath as mp

from fast_cdf_constants import coq_constant

ROOT = Path(__file__).resolve().parents[1]
mp.mp.prec = 200
LIMIT = float.fromhex('0x1.921fb54442d18p-1')


def coefficients():
    upper = mp.mpf(LIMIT) ** 2
    functions = [lambda z: mp.sin(mp.sqrt(z)) / mp.sqrt(z) if z else mp.mpf(1),
                 lambda z: mp.cos(mp.sqrt(z))]
    return [[float(c) for c in reversed(mp.chebyfit(f, [0, upper], 6))] for f in functions]


def polynomial(names, z):
    p = names[-1]
    for c in reversed(names[:-1]):
        p = f'({c} + {z} * {p})'
    return p


def outputs():
    sine, cosine = coefficients()
    rust = '//! Generated by generators/fast_random_constants.py at 200 bits; do not edit.\n'
    coq = ('(** Generated by generators/fast_random_constants.py; do not edit. *)\n'
           'From Coq Require Import Reals ZArith.\n'
           'From Flocq Require Import Core IEEE754.Binary IEEE754.Bits.\n'
           'From Binary64 Require Import IEEE64 Encodings.\n'
           'From Gappa Require Import Gappa_library.\n'
           'Require Import StageGappa.\nOpen Scope R_scope.\n')
    for name, values in [('SIN', sine), ('COS', cosine)]:
        rust += f'pub(super) const {name}: [f64; 6] = [\n'
        for i, value in enumerate(values):
            bits = struct.pack('>d', value).hex()
            rust += f'    f64::from_bits(0x{bits}),\n'
            key = f'bm_{name.lower()}{i}'
            declaration = coq_constant(key, value)
            declaration = declaration.replace(
                'Proof. apply word_value_ok; vm_compute; reflexivity. Qed.',
                f'Proof. rewrite {key}_val. unfold float2R, F2R. simpl. bpow_num. field. Qed.')
            coq += declaration
        rust += '];\n'
    result = {'crates/morphiq-numerics/src/fast/random_tables.rs': rust,
              'formal/fast/FastRandomConstants.v': coq}
    for name, values in [('sin', sine), ('cos', cosine)]:
        gappa = '# Generated by generators/fast_random_constants.py.\n@rnd = float<ieee_64, ne>;\n'
        for i, value in enumerate(values):
            gappa += f'c{i} = {value.hex()};\n'
        gappa += 'x = rnd(xx);\nz = rnd(x*x);\nZ = x*x;\n'
        gappa += 'p5 = c5;\n'
        for i in reversed(range(5)):
            gappa += f'p{i} = rnd(c{i} + rnd(z*p{i+1}));\n'
        ideal = polynomial([f'c{i}' for i in range(6)], 'Z')
        gappa += f'P = {ideal};\n'
        gappa += 'v = rnd(x*p0);\nV = x*P;\n' if name == 'sin' else 'v = p0;\nV = P;\n'
        gappa += f'{{ xx in [0, {LIMIT.hex()}] -> v - V in [-0x1p-51, 0x1p-51] }}\n'
        result[f'formal/normal/normal_pair_{name}.g'] = gappa
    sollya = ('// Generated by generators/fast_random_constants.py; absolute approximation errors.\n'
              'prec = 300;\ndisplay = hexadecimal;\n'
              'procedure fact(k) { var r, i; r = 1; for i from 2 to k do r = r*i; return r; };\n'
              f'T = {LIMIT.hex()};\nS = [0; T^2];\nTS = 0; TC = 0;\n'
              'for n from 20 to 0 by -1 do TS = TS*x + (-1)^n/fact(2*n+1);\n'
              'for n from 20 to 0 by -1 do TC = TC*x + (-1)^n/fact(2*n);\n')
    for name, values, target, fact in [('sin', sine, 'TS', 43), ('cos', cosine, 'TC', 42)]:
        sollya += f'p = {polynomial([x.hex() for x in values], "x")};\n'
        sollya += f'r = (T^2)^21/fact({fact});\n'
        sollya += f'print("{name}_error_bound", round(sup(supnorm(p, {target}, S, absolute, 2^-30)) + r, 24, RU));\n'
    sollya += 'quit;\n'
    result['generators/normal_random_poly.sollya'] = sollya
    return result


def main():
    for name, text in outputs().items():
        path = ROOT / name
        if '--check' in sys.argv:
            if path.read_text() != text:
                sys.exit(f'{path} differs from a fresh generation')
        else:
            path.write_text(text)


if __name__ == '__main__':
    main()
