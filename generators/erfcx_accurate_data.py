#!/usr/bin/env python3
"""Transcribe generated erfcx Q256 words for kernel-checked accurate proofs.

The constants originate in erfcx/accurate_tables.py. This script only decodes
its Rust output; the Coq proofs independently bound their mathematical error.
"""
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
source = (ROOT / 'crates/morphiq-numerics/src/erfcx/accurate_tables.rs').read_text()
names = [('CS', 1), ('C2', 1), ('LN2_128', 1), ('F_AT_C', 177), ('RECIP', 100), ('T2', 128)]
out = '''(** Generated by generators/erfcx_accurate_data.py from accurate_tables.rs. *)
From Coq Require Import ZArith List Bool Lia.
From Q Require Import Q256.
From Q Require Limbs.
Import ListNotations.
Open Scope Z_scope.
Definition constant := (list Z * Z)%type.
Definition constant_q (c : constant) := new false (fst c) (snd c).
Definition constant_check (c : constant) :=
  Nat.eqb (length (fst c)) 4 && forallb (fun l => (0<=?l) && (l<?2^64)) (fst c).
Lemma constant_check_ok c : constant_check c=true -> ok4 (fst c).
Proof.
  unfold constant_check. rewrite andb_true_iff,Nat.eqb_eq. intros [Length Words].
  split; [ | exact Length]. apply Forall_forall. intros l In.
  apply forallb_forall with (x:=l) in Words; [ | exact In].
  apply andb_true_iff in Words. destruct Words as [Lo Hi].
  apply Z.leb_le in Lo. apply Z.ltb_lt in Hi. unfold Limbs.B. split; assumption.
Qed.
'''
for name, count in names:
    body = source.split('pub const '+name+':', 1)[1].split('=', 1)[1].split(';', 1)[0]
    rows = re.findall(r'\(\s*\[([^]]+)\],\s*(-?\d+),?\s*\)', body)
    assert len(rows) == count, (name, len(rows))
    values = []
    for words, exponent in rows:
        limbs = [int(x,16) for x in re.findall(r'0x[0-9a-f]+', words)]
        assert len(limbs)==4
        values.append('(['+'; '.join(map(str,limbs))+'], '+exponent+')')
    key = name.lower()
    if count == 1:
        out += f'Definition {key}_data : constant := {values[0]}.\n'
        out += f'Lemma {key}_data_checked : constant_check {key}_data=true.\nProof. vm_compute; reflexivity. Qed.\n'
    else:
        out += f'Definition {key}_data : list constant := [\n '+ ';\n '.join(values)+ '\n].\n'
        out += f'Lemma {key}_data_length : length {key}_data={count}%nat.\nProof. reflexivity. Qed.\n'
        out += f'Lemma {key}_data_checks : forallb constant_check {key}_data=true.\nProof. vm_compute; reflexivity. Qed.\n'
        out += f'''Lemma {key}_data_checked i : (i<{count})%nat ->
  constant_check (nth i {key}_data ([],0))=true.
Proof.
  intros I. pose proof {key}_data_checks as Checks.
  apply forallb_forall with (x:=nth i {key}_data ([],0)) in Checks; [exact Checks | ].
  apply nth_In. rewrite {key}_data_length. exact I.
Qed.
'''
dest = ROOT / 'formal/erfcx/ErfcxAccurateData.v'
if '--check' in sys.argv:
    assert dest.read_text() == out, f'{dest} differs'
else:
    dest.write_text(out)

trans = '''(** Generated by generators/erfcx_accurate_data.py. CoqInterval checks the mathematical values. *)
From Coq Require Import Reals ZArith Lia Lra List.
From Flocq Require Import Core.
From Interval Require Import Tactic.
From Q Require Import Q256 Q256Real.
From Q Require Limbs.
Require Import StageGappa ErfcxAccurateData ErfcxAccurateConstants.
Import ListNotations.
Open Scope R_scope.
Definition q_logstep := constant_q ln2_128_data.
Definition q_exp_table j := constant_q (nth j t2_data ([],0%Z)).
Theorem q_logstep_ok : valid q_logstep /\\
  Rabs (qval q_logstep-ln 2/128)<=bpow radix2 (-263).
Proof.
  destruct (constant_q_ok _ ln2_128_data_checked) as [Q Value].
  split; [exact Q | ]. unfold q_logstep. rewrite Value.
  cbn [ln2_128_data fst snd].
'''
body = source.split('pub const LN2_128:',1)[1].split('=',1)[1].split(';',1)[0]
limbs = [int(x,16) for x in re.findall(r'0x[0-9a-f]+', body)]
mantissa = sum(x<<(64*i) for i,x in enumerate(limbs))
trans += f'''  change (Limbs.v _) with {mantissa}%Z.
  bpow_num. apply Rabs_le; split; interval with (i_prec 400).
Qed.
'''
body = source.split('pub const T2:',1)[1].split('=',1)[1].split(';',1)[0]
rows = re.findall(r'\(\s*\[([^]]+)\],\s*(-?\d+),?\s*\)',body)
for j,(words,exponent) in enumerate(rows):
    limbs=[int(x,16) for x in re.findall(r'0x[0-9a-f]+',words)]
    mantissa=sum(x<<(64*i) for i,x in enumerate(limbs))
    trans += f'''Lemma exp_table_error_{j:03} :
  Rabs (qval (q_exp_table {j})/exp (INR {j}*ln 2/128)-1)<=bpow radix2 (-255).
Proof.
  destruct (constant_q_ok _ (t2_data_checked {j} ltac:(lia))) as [Q Value].
  unfold q_exp_table. rewrite Value,INR_IZR_INZ.
  change (Rabs (({mantissa}*bpow radix2 ({exponent}))/exp ({j}*ln 2/128)-1)<=bpow radix2 (-255)).
  bpow_num. apply Rabs_le; split; interval with (i_prec 400).
Qed.
'''
trans += '''Theorem q_exp_table_ok j : (j<128)%nat -> valid (q_exp_table j) /\\
  Rabs (qval (q_exp_table j)/exp (INR j*ln 2/128)-1)<=bpow radix2 (-255).
Proof.
  intros J. split.
  - exact (proj1 (constant_q_ok _ (t2_data_checked j J))).
  -
'''
for j in range(128):
    trans+=f'    destruct j as [|j]; [exact exp_table_error_{j:03} | ].\n'
trans+='    lia.\nQed.\n'
dest = ROOT / 'formal/erfcx/ErfcxAccurateTranscendentals.v'
if '--check' in sys.argv:
    assert dest.read_text() == trans, f'{dest} differs'
else:
    dest.write_text(trans)
