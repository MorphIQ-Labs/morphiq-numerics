#!/usr/bin/env python3
"""Generate the far log-CDF evaluation certificate and proof coefficients.

Exact rational algebra supplies the logarithmic Mills coefficients. Binary64
encodings are regenerated at 600 and 1000 bits. The analytic remainder is
proved independently in NormalLogTailApprox.v.
"""
import pathlib
import sys
import mpmath as mp
from normal_constants import bits, log_tail_coefficients

ROOT = pathlib.Path(__file__).resolve().parents[1]


def horner(coefficients, variable):
    result = coefficients[-1]
    for coefficient in reversed(coefficients[:-1]):
        result = f'({coefficient}+{variable}*{result})'
    return f'{variable}*{result}'


def generate(precision):
    with mp.workprec(precision):
        rational = log_tail_coefficients()
        values = [float(mp.mpf(c.numerator)/c.denominator) for c in rational]
        coq = '''(** Generated by generators/normal_log_tail.py. *)
From Coq Require Import Reals ZArith Lia.
From Flocq Require Import Core IEEE754.Bits.
From Binary64 Require Import IEEE64 Encodings.
From Gappa Require Import Gappa_library.
Require Import StageGappa.
Open Scope R_scope.
'''
        for i, value in enumerate(values):
            encoded = bits(value)
            numerator, denominator = value.as_integer_ratio()
            real = f'float2R (Float2 ({numerator}) ({-(denominator.bit_length()-1)}))' if denominator != 1 else str(numerator)
            exponent = -(denominator.bit_length()-1)
            negative = value < 0
            mantissa = abs(numerator)
            while mantissa < 1 << 52:
                mantissa <<= 1
                exponent -= 1
            coq += fr'''Definition normal_log_tail_c{i} := b64_of_bits {encoded}.
Definition normal_log_tail_c{i}_r : R := {real}.
Lemma normal_log_tail_c{i}_ok : finite normal_log_tail_c{i} /\
  B normal_log_tail_c{i}=normal_log_tail_c{i}_r.
Proof.
  split.
  - exact(bits_finite {encoded} {str(negative).lower()} {mantissa} ({exponent}) eq_refl).
  - unfold normal_log_tail_c{i},normal_log_tail_c{i}_r.
    rewrite(bits_val {encoded} {str(negative).lower()} {mantissa} {-exponent} eq_refl).
    unfold float2R,F2R;cbn [Fnum Fexp];simpl;bpow_num;field.
Qed.
'''
        ieee = 'normal_log_tail_c7'
        rounded = 'normal_log_tail_c7_r'
        for i in reversed(range(7)):
            ieee = f'(fadd normal_log_tail_c{i} (fmul u {ieee}))'
            rounded = f'rn(normal_log_tail_c{i}_r+rn(u*({rounded})))'
        coq += f'Definition normal_log_tail_horner64 u := {ieee}.\n'
        coq += f'Definition normal_log_tail_horner_r u := {rounded}.\n'
        certificate = '''# Generated by generators/normal_log_tail.py; do not edit.
# Rounded reciprocal, square and Horner evaluation, including coefficient rounding.
@rnd = float<ieee_64, ne>;
r = rnd(z);
u = rnd(r*r);
'''
        for i, value in enumerate(values):
            certificate += f'c{i} = {value.hex()};\n'
        certificate += 'p7 = c7;\n'
        for i in reversed(range(7)):
            certificate += f'p{i} = rnd(c{i}+rnd(u*p{i+1}));\n'
        certificate += 'p = rnd(u*p0);\n'
        exact = [f'({c.numerator}/{c.denominator})' if c.denominator != 1 else str(c.numerator) for c in rational]
        certificate += f'P = {horner(exact, "(z*z)")};\n'
        certificate += '{ z in [1b-45, 0.027027027027027028] -> p-P in [-1b-61, 1b-61] }\n'
        mills = []
        term = 1
        for n in range(1, 9):
            term *= -(2*n-1)
            mills.append(str(term))
        sollya = '''// Generated by generators/normal_log_tail.py; do not edit.
// Logarithmic Mills correction (docs/normal.md, negative far tail).
// Coq independently checks this bound and the improper-integral remainder.
prec = 300;
display = hexadecimal;
I = [0; 1/1369];
'''
        sollya += f'S = 1+{horner(mills, "x")};\nP = {horner(exact, "x")};\n'
        sollya += '''fit = sup(supnorm(P, -log(S), I, absolute, 2^-20));
print("absolute_error_bound", round(fit, 24, RU));
quit;
'''
        return coq, certificate, sollya


def main():
    generated = generate(600)
    assert generated == generate(1000), 'tail encodings are not precision-stable'
    paths = ['formal/normal/NormalLogTailData.v', 'formal/normal/log_tail_polynomial.g',
             'generators/normal_poly.sollya']
    for name, text in zip(paths, generated):
        out = ROOT/name
        if '--check' in sys.argv:
            assert out.read_text() == text, f'{name} differs'
        else:
            out.write_text(text)
    print('normal log tail: exact rational coefficients, 600/1000-bit encodings')


if __name__ == '__main__':
    main()
