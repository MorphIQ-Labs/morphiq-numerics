#!/usr/bin/env python3
"""Generate conditional evaluation models for the migration experiments.

Run with --check to verify committed models, then Gappa 1.4.1 on each .g.
These are NOT end-to-end proofs. In particular the Rust transcription,
reduction hypotheses, rounding-test margin and scaling domains still need
binding proofs. No certificate here authorizes production use.

Coefficients/approximation error come from the existing generated exp polynomial.
ln error-composition hypotheses come from the existing stage-H analysis; their
validity over ln's extended exponent domain remains a separate proof obligation.
"""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = pathlib.Path(__file__).resolve().parent / 'certificates'
p = dict(line.split() for line in (ROOT / 'generators/exp_poly.out').read_text().splitlines())

MODELS = {
    'exp2_a.g': f'''# exp2 stage A: the exp stage-A evaluation with a wider reduction error.
# R=d*ln(2), |d|<=2^-10. dr=d*(RN(ln(2))-ln(2)); |dr|<=2^-65
# follows from |RN(ln(2))-ln(2)|<=2^-55. r=RN(R+dr).
# The mean-value term is widened to 2^-73. Binding these hypotheses to
# the dyadic Rust reduction, including subnormal d, remains required.
# Generated by research/stage-migrations/certificates.py.
@rnd = float<ieee_64, ne>;
d3 = {p['d3']};
d4 = {p['d4']};
d5 = {p['d5']};
r = rnd(R + dr);
t4 rnd= d4 + r * d5;
t3 rnd= d3 + r * t4;
h rnd= 0.5 + r * t3;
r2 rnd= r * r;
w rnd= r2 * h;
u rnd= r + w;
prod rnd= th * u;
fl rnd= tl + prod;
Qr = r * r * (0.5 + r * (d3 + r * (d4 + r * d5)));
QR = Qr + m;
expR = 1 + R + QR + a;
T = th + tl - Dt;
Y = th + fl;
{{ R in [-0.000677, 0.000677] /\\ dr in [-1b-65, 1b-65]
  /\\ a in [-{p['stage_error_bound']}, {p['stage_error_bound']}] /\\ m in [-1b-73, 1b-73]
  /\\ th in [1, 2] /\\ tl in [-1b-53, 1b-53] /\\ Dt in [-1b-104, 1b-104]
  -> Y - T * expR in [-1b-60, 1b-60] }}
Y - T * expR -> th * (r - R) - th * m + th * (u - (r + Qr)) - th * a - tl * (R + QR + a)
  + (fl - (tl + th * u)) + Dt * expR;
fl - (tl + th * u) -> (fl - (tl + prod)) + (prod - th * u);
u - (r + Qr) -> (u - (r + w)) + (w - Qr);
r - R -> (r - (R + dr)) + dr;
''',
    'ln_composition.g': r'''# ln's prospective error composition after exact reduction and Fast2Sum.
# The identity is err = z^2 * Gz + s * Gs. Rounding deltas: d0 for
# ln0=RN(el+tl), d1 for pre=RN(e1+ln0), d2 for lo=RN(pre+q).
# tau=(N-ln1-el-tl)/s; kap=ln0/s; eta=e1/s.
# The ranges below come from ln_1p's existing H analysis. A proof that they
# hold for the new full-exponent ln reduction is still required.
# Generated by research/stage-migrations/certificates.py.
Gz = t3 - t4 - d2 * (Pz + t4);
Gs = tau - d0 * kap / (1 + d0) - d1 * (eta + kap) - d2 * (1 + d1) * (eta + kap);
{ t3 in [-37b-56, 37b-56] /\ t4 in [-577b-61, 577b-61]
  /\ Pz in [-513b-10, -511b-10]
  /\ tau in [-732b-96, 732b-96] /\ kap in [-732b-43, 732b-43]
  /\ eta in [-1b-53, 1b-53]
  /\ d0 in [-1b-53, 1b-53] /\ d1 in [-1b-53, 1b-53] /\ d2 in [-1b-53, 1b-53]
  -> Gz in [-1b-50, 1b-50] /\ Gs in [-1b-82, 1b-82] }
''',
    'expm1_margin.g': r'''# Conditional budget for reconstruction after an error-free subtraction.
# a=|e|+|l|; base is 2^-59 (A) or 2^-68 (B); assume the exponential
# approximation error is at most base/2. Fold and test roundings cost at
# most (2u+u^2)*a + u*eps, with all absolute underflow terms <=2^-999.
# eps models the three roundings in base+(|e|+|l|)*2^-51.
# The error-free subtraction, actual relative/absolute rounding model,
# scaling, and the input screens' hypotheses still require binding proofs.
# Generated by research/stage-migrations/certificates.py.
u = 1b-53;
eps = (base + a * (1 + d0) * (4 * u) * (1 + d1)) * (1 + d2);
margin = base / 2 + a * (2 * u + u * u) + u * eps - eps + 1b-999;
{ a in [0, 4] /\ base in [1b-68, 1b-59]
  /\ d0 in [-1b-53, 1b-53] /\ d1 in [-1b-53, 1b-53] /\ d2 in [-1b-53, 1b-53]
  -> margin <= 0 }
margin -> base * (1/2 - (1 + d2) * (1 - u))
  + a * (2 * u + u * u - 4 * u * (1 + d0) * (1 + d1) * (1 + d2) * (1 - u)) + 1b-999;
''',
}


def main():
    check = sys.argv[1:] == ['--check']
    if sys.argv[1:] not in ([], ['--check']):
        sys.exit('usage: certificates.py [--check]')
    OUT.mkdir(exist_ok=True)
    for name, content in MODELS.items():
        path = OUT / name
        if check:
            if not path.exists() or path.read_text() != content:
                sys.exit(f'{path}: differs from generator')
        else:
            path.write_text(content)
    print(f'{len(MODELS)} conditional models {"checked" if check else "written"}')


if __name__ == '__main__':
    main()
